def main():
    sheet = json.loads((ROOT / "otk/sheets/posn2560_physics/sheet.json").read_text("utf-8"))
    destination = ROOT / "otk/knowledge/physics"
    destination.mkdir(exist_ok=True)
    for item in sheet["items"]:
        n = item["number"]
        slug, statement, first, second = UNITS[n]
        path = destination / f"{slug}.json"
        raw = (
            json.loads(path.read_text("utf-8"))
            if path.exists()
            else {
                "subject": "ฟิสิกส์",
                "topic": item["topic"],
                "level": sheet["level"],
                "units": [],
            }
        )
        uid = f"phys.{slug.replace('-', '_')}.procedure"
        unit = {
            "id": uid,
            "kind": "procedure",
            "title": item["title"],
            "statement": statement,
            "steps": [first, second],
            "sources": [{"sheet": SOURCE, "item": n}],
            "covered_by": [item["generator"]],
            "note": item["note"],
        }
        previous = next((u for u in raw["units"] if u["id"] == uid), None)
        if previous is None:
            raw["units"].append(unit)
        else:
            for source in unit["sources"]:
                if source not in previous["sources"]:
                    previous["sources"].append(source)
            for key in unit["covered_by"]:
                if key not in previous["covered_by"]:
                    previous["covered_by"].append(key)
        path.write_text(json.dumps(raw, ensure_ascii=False, indent=2) + "\n", "utf-8")


if __name__ == "__main__":
    main()
