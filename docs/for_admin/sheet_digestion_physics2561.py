def main():
    sheet = json.loads((ROOT / "otk/sheets/posn2561_physics/sheet.json").read_text("utf-8"))
    for item in sheet["items"]:
        n = item["number"]
        slug, statement, first, second = UNITS[n]
        path = ROOT / "otk/knowledge/physics" / f"{slug}.json"
        raw = (
            json.loads(path.read_text("utf-8"))
            if path.exists()
            else {
                "subject": sheet["subject"],
                "topic": item["topic"],
                "level": sheet["level"],
                "units": [],
            }
        )
        uid = f"phys.{slug.replace('-', '_')}.procedure"
        unit = next((u for u in raw["units"] if u["id"] == uid), None)
        if unit is None:
            unit = {
                "id": uid,
                "kind": "procedure",
                "title": item["title"],
                "statement": statement,
                "steps": [first, second],
                "sources": [],
                "covered_by": [],
                "note": item["note"],
            }
            raw["units"].append(unit)
        # The shared pulley unit keeps both stopping regimes in its statement.
        if n == 5 and statement not in unit["statement"]:
            unit["statement"] += "; " + statement
            unit["steps"].append(second)
        source = {"sheet": SOURCE, "item": n}
        if source not in unit["sources"]:
            unit["sources"].append(source)
        if item["generator"] not in unit["covered_by"]:
            unit["covered_by"].append(item["generator"])
        path.write_text(json.dumps(raw, ensure_ascii=False, indent=2) + "\n", "utf-8")


if __name__ == "__main__":
    main()
