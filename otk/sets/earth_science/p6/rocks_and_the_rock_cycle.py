class RockPhotoType(QuestionType):
    """Base: show one specimen photo, ask one fact about it.

    Both subclasses draw from the same ``ROCK_PHOTOS`` table and differ only in
    which field is the answer and which labels the wrong choices come from — so
    the distractors are always other *real* rocks (or groups) in the สาระ.
    """

    STEM = ""
    ALT = "ภาพตัวอย่างหิน"

    @abstractmethod
    def answer(self, photo: RockPhoto) -> str:
        """The fact this type asks about."""

    @abstractmethod
    def pool(self) -> list[str]:
        """Every label a choice may show; ``label_pool`` drops the correct one."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        photo = rng.choice(ROCK_PHOTOS)
        return GeneratedQuestion(
            stem=[
                image(photo.asset_id, alt=self.ALT),
                text(f"{self.STEM}\nข้อมูลประกอบ: {ROCK_EVIDENCE[photo.rock]}"),
            ],
            correct=[text(self.answer(photo))],
            distractors=label_pool(self.pool()),
            topic=self.topic,
        )


