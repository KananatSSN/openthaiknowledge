@question_type(
    "comp.info_credibility_fluency",
    display_name={"th": "เลือกแหล่งข้อมูลที่น่าเชื่อถือที่สุด"},
    level=M3, subject=SUBJECT, topic=CREDIBILITY_TOPIC,
)
class InfoCredibilityFluency(QuestionType):
    def build(self, rng: Random, **params):
        topic, best, weaker = rng.choice(SOURCES)
        return _labelled(
            stem=f"ต้องการค้นหา{topic} แหล่งข้อมูลใดน่าเชื่อถือที่สุด",
            correct=best, wrongs=tuple(weaker),
            hint="แหล่งที่น่าเชื่อถือที่สุดคือหน่วยงานที่รับผิดชอบหรือเชี่ยวชาญเรื่องนั้นโดยตรงและเผยแพร่อย่างเป็นทางการ",
            topic=CREDIBILITY_TOPIC,
        )


