@question_type(
    "comp.internet_rules_foundation",
    display_name={"th": "บอกข้อมูลส่วนตัวที่ไม่ควรเปิดเผยทางอินเทอร์เน็ต"},
    level=THIRD, subject=SUBJECT, topic=INTERNET_TOPIC,
)
class InternetRulesFoundation(QuestionType):
    def build(self, rng: Random, **params):
        if rng.random() < 0.5:
            return _labelled(
                stem="ข้อใดเป็นข้อมูลส่วนตัวที่ไม่ควรเปิดเผยให้คนแปลกหน้าทางอินเทอร์เน็ต",
                correct=rng.choice(PRIVATE), wrongs=tuple(SHAREABLE),
                hint=PRIVATE_HINT, topic=INTERNET_TOPIC,
            )
        return _labelled(
            stem="ข้อใดเป็นข้อมูลที่แบ่งปันทางอินเทอร์เน็ตได้โดยไม่เปิดเผยตัวตน",
            correct=rng.choice(SHAREABLE), wrongs=tuple(PRIVATE),
            hint=PRIVATE_HINT, topic=INTERNET_TOPIC,
        )


@question_type(
    "comp.internet_rules_fluency",
    display_name={"th": "บอกเหตุผลของข้อตกลงในการใช้อินเทอร์เน็ต"},
    level=THIRD, subject=SUBJECT, topic=INTERNET_TOPIC,
)
class InternetRulesFluency(QuestionType):
    def build(self, rng: Random, **params):
        index = rng.randrange(len(INTERNET_RULES))
        rule, reason = INTERNET_RULES[index]
        others = rng.sample([row for i, row in enumerate(INTERNET_RULES) if i != index], 3)
        hint = "ถามว่าข้อตกลงข้อนั้นป้องกันอันตรายแบบใด ต่อตัวเรา ต่อเครื่อง หรือต่อผู้อื่น"
        if rng.random() < 0.5:
            return _labelled(
                stem=f"เพราะเหตุใดจึงควร{rule}",
                correct=reason, wrongs=tuple(r for _, r in others), hint=hint, topic=INTERNET_TOPIC,
            )
        return _labelled(
            stem=f"ข้อตกลงใดในการใช้อินเทอร์เน็ตมีเหตุผลว่า “{reason}”",
            correct=rule, wrongs=tuple(r for r, _ in others), hint=hint, topic=INTERNET_TOPIC,
        )


