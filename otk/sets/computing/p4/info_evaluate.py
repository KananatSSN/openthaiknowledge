@question_type(
    "comp.info_evaluate_foundation",
    display_name={"th": "แยกข้อมูลกับสารสนเทศ"},
    level=P4, subject=SUBJECT, topic=INFO_TOPIC,
)
class InfoEvaluateFoundation(QuestionType):
    def build(self, rng: Random, **params):
        return _pick_one(rng, good=INFORMATION, bad=RAW_DATA,
                         good_stem="ข้อใดเป็นสารสนเทศ คือข้อมูลที่ผ่านการประมวลผลแล้ว",
                         bad_stem="ข้อใดเป็นข้อมูลที่ยังไม่ผ่านการประมวลผล",
                         hint="ข้อมูลคือสิ่งที่เก็บมาตามจริงทีละรายการ สารสนเทศคือผลที่ได้จากการนำข้อมูลมาคำนวณ "
                              "เรียงลำดับ สรุป หรือทำเป็นแผนภูมิ",
                         topic=INFO_TOPIC)


