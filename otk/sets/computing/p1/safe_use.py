@question_type(
    "comp.safe_use_foundation",
    display_name={"th": "บอกการใช้คอมพิวเตอร์ที่ปลอดภัยและไม่ปลอดภัย"},
    level=FIRST_PRIMARY, subject=SUBJECT, topic=SAFETY_TOPIC,
)
class SafeUseFoundation(QuestionType):
    """Pick the one right practice among wrong ones, or the reverse."""

    def build(self, rng: Random, **params):
        if rng.random() < 0.5:
            return _labelled(
                stem="ข้อใดเป็นการใช้คอมพิวเตอร์ที่ถูกต้องและปลอดภัย",
                correct=rng.choice(SAFE), wrongs=tuple(UNSAFE),
                hint=SAFETY_HINT, topic=SAFETY_TOPIC,
            )
        return _labelled(
            stem="ข้อใดเป็นสิ่งที่ไม่ควรทำเมื่อใช้คอมพิวเตอร์",
            correct=rng.choice(UNSAFE), wrongs=tuple(SAFE),
            hint=SAFETY_HINT, topic=SAFETY_TOPIC,
        )


@question_type(
    "comp.safe_use_fluency",
    display_name={"th": "บอกเหตุผลของข้อตกลงในการใช้คอมพิวเตอร์"},
    level=FIRST_PRIMARY, subject=SUBJECT, topic=SAFETY_TOPIC,
)
class SafeUseFluency(QuestionType):
    """Match a practice to its reason, in either direction."""

    def build(self, rng: Random, **params):
        index = rng.randrange(len(REASONS))
        practice, reason = REASONS[index]
        others = rng.sample([row for i, row in enumerate(REASONS) if i != index], 3)
        if rng.random() < 0.5:
            return _labelled(
                stem=f"เพราะเหตุใดจึงควร{practice}",
                correct=reason, wrongs=tuple(r for _, r in others),
                hint=SAFETY_HINT, topic=SAFETY_TOPIC,
            )
        return _labelled(
            stem=f"ข้อใดเป็นการปฏิบัติที่มีเหตุผลว่า “{reason}”",
            correct=practice, wrongs=tuple(p for p, _ in others),
            hint=SAFETY_HINT, topic=SAFETY_TOPIC,
        )


@question_type(
    "comp.safe_use_application",
    display_name={"th": "เลือกวิธีปฏิบัติที่เหมาะสมเมื่อใช้คอมพิวเตอร์และอินเทอร์เน็ต"},
    level=FIRST_PRIMARY, subject=SUBJECT, topic=SAFETY_TOPIC,
)
class SafeUseApplication(QuestionType):
    """What to do when something goes wrong."""

    def build(self, rng: Random, **params):
        situation, correct, wrongs = rng.choice(SITUATIONS)
        return _labelled(
            stem=f"{situation} ควรทำอย่างไร",
            correct=correct, wrongs=tuple(wrongs),
            hint="เมื่อไม่แน่ใจหรือมีสิ่งผิดปกติ ให้หยุด ไม่ให้ข้อมูลส่วนตัว และบอกครูหรือผู้ปกครอง",
            topic=SAFETY_TOPIC,
        )


