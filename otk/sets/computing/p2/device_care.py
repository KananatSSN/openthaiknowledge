@question_type(
    "comp.device_care_foundation",
    display_name={"th": "บอกวิธีดูแลรักษาอุปกรณ์คอมพิวเตอร์"},
    level=SECOND, subject=SUBJECT, topic=CARE_TOPIC,
)
class DeviceCareFoundation(QuestionType):
    """The right way to look after a named device."""

    def build(self, rng: Random, **params):
        device = rng.choice(list(DEVICES))
        care, harms = DEVICES[device]
        if rng.random() < 0.5:
            other = rng.choice([d for d in DEVICES if d != device])
            return _labelled(
                stem=f"ข้อใดเป็นวิธีดูแลรักษา{device}ที่ถูกต้อง",
                correct=care, wrongs=(*harms, DEVICES[other][1][rng.randrange(2)]),
                hint=CARE_HINT, topic=CARE_TOPIC,
            )
        others = [DEVICES[d][0] for d in DEVICES if d != device]
        return _labelled(
            stem=f"ข้อใดเป็นการใช้{device}ที่ทำให้{device}เสียหาย",
            correct=rng.choice(harms), wrongs=tuple(rng.sample(others, 2)) + (care,),
            hint=CARE_HINT, topic=CARE_TOPIC,
        )


@question_type(
    "comp.device_care_fluency",
    display_name={"th": "บอกเหตุผลของข้อตกลงในห้องคอมพิวเตอร์"},
    level=SECOND, subject=SUBJECT, topic=CARE_TOPIC,
)
class DeviceCareFluency(QuestionType):
    """Match an agreement to what it protects, in either direction."""

    def build(self, rng: Random, **params):
        index = rng.randrange(len(AGREEMENTS))
        rule, reason = AGREEMENTS[index]
        others = rng.sample([row for i, row in enumerate(AGREEMENTS) if i != index], 3)
        hint = "ถามว่าถ้าไม่ทำตามข้อตกลงข้อนี้ จะเกิดปัญหาอะไรกับเครื่อง กับงาน หรือกับเพื่อน"
        if rng.random() < 0.5:
            return _labelled(
                stem=f"ข้อตกลงของห้องคอมพิวเตอร์ “{rule}” มีไว้เพื่ออะไร",
                correct=reason, wrongs=tuple(r for _, r in others), hint=hint, topic=CARE_TOPIC,
            )
        return _labelled(
            stem=f"ข้อตกลงใดของห้องคอมพิวเตอร์มีไว้เพื่อให้{reason}",
            correct=rule, wrongs=tuple(r for r, _ in others), hint=hint, topic=CARE_TOPIC,
        )


