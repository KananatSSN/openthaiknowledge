@question_type(
    "comp.file_folders_foundation",
    display_name={"th": "จัดไฟล์เข้าโฟลเดอร์ตามหมวดหมู่"},
    level=P2, subject=SUBJECT, topic=FOLDER_TOPIC,
)
class FileFoldersFoundation(QuestionType):
    def build(self, rng: Random, **params):
        scheme, folders = rng.choice(FOLDER_SCHEMES)
        names = [name for name, _ in folders]
        name, files = rng.choice(folders)
        item = rng.choice(files)
        if rng.random() < 0.5:
            return _labelled(stem=f"นักเรียนจัดไฟล์เป็น{scheme} ได้แก่ {' '.join(names)} ไฟล์ “{item}” ควรอยู่ในโฟลเดอร์ใด",
                             correct=name, wrongs=tuple(n for n in names if n != name),
                             hint=FOLDER_HINT, topic=FOLDER_TOPIC)
        others = [f for n, fs in folders if n != name for f in fs]
        return _labelled(stem=f"นักเรียนจัดไฟล์เป็น{scheme} ไฟล์ใดควรอยู่ในโฟลเดอร์ “{name}”",
                         correct=item, wrongs=tuple(others), hint=FOLDER_HINT, topic=FOLDER_TOPIC)


@question_type(
    "comp.file_folders_fluency",
    display_name={"th": "ตั้งชื่อไฟล์ให้ค้นหาได้ง่าย"},
    level=P2, subject=SUBJECT, topic=FOLDER_TOPIC,
)
class FileFoldersFluency(QuestionType):
    def build(self, rng: Random, **params):
        what, good = rng.choice(NAMES)
        misleading = tuple(name for _, name in NAMES if name != good)
        return _labelled(stem=f"นักเรียนบันทึกไฟล์{what} ควรตั้งชื่อไฟล์ว่าอะไรจึงจะค้นหาได้ง่ายในภายหลัง",
                         correct=good, wrongs=(*POOR_NAMES, *misleading),
                         hint="ชื่อไฟล์ที่ดีบอกได้ว่าไฟล์นั้นเป็นเรื่องอะไร ชื่อที่ไม่มีความหมาย เช่น ไฟล์ใหม่ งาน1 ทำให้หาไม่เจอ",
                         topic=FOLDER_TOPIC)


