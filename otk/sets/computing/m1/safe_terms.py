def strong_password(rng: Random) -> str:
    first, second = rng.sample(WORDS, 2)
    return (f"{first}{rng.choice(SYMBOLS)}{second.lower()}{rng.randint(10, 99)}"
            f"{rng.choice(SYMBOLS)}")


def weak_passwords(rng: Random) -> list[str]:
    """Short guessable ones, and long ones that are just as guessable: a name
    and birth year typed twice, a keyboard row, one word repeated."""
    word = rng.choice(WORDS).lower()
    name, year = rng.choice(THAI_NAMES), rng.randint(2550, 2560)
    return ["12345678", "password1", f"{name}{year}", f"{word}{word}", "qwertyui",
            f"{name}{year}{name}", "qwertyuiop123456", f"{word}{word}{word}", "password12345678"]


