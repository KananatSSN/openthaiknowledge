@question_type(
    "comp.safe_terms_foundation",
    display_name={"th": "เลือกรหัสผ่านที่ปลอดภัย"},
    level=M1, subject=SUBJECT, topic=TERMS_TOPIC,
)
class SafeTermsFoundation(QuestionType):
    def build(self, rng: Random, **params):
        return _labelled(
            stem="รหัสผ่านใดปลอดภัยที่สุด",
            correct=strong_password(rng), wrongs=tuple(weak_passwords(rng)),
            hint=("รหัสผ่านที่ปลอดภัยยาวอย่างน้อย 12 ตัวอักษร ผสมตัวพิมพ์ใหญ่ ตัวพิมพ์เล็ก ตัวเลข "
                  "และสัญลักษณ์ ไม่ใช่ชื่อ วันเกิด หรือตัวอักษรเรียงบนแป้นพิมพ์"),
            topic=TERMS_TOPIC,
        )


@question_type(
    "comp.safe_terms_fluency",
    display_name={"th": "พิจารณาสิทธิ์ที่แอปขอและสังเกตการหลอกลวง"},
    level=M1, subject=SUBJECT, topic=TERMS_TOPIC,
)
class SafeTermsFluency(QuestionType):
    def build(self, rng: Random, **params):
        if rng.random() < 0.5:
            app, permission, needed = rng.choice(APP_PERMISSIONS)
            correct = ALLOW if needed else DENY
            return _labelled(
                stem=f"แอปพลิเคชัน{app}ขอสิทธิ์เข้าถึง{permission}ในโทรศัพท์ ควรทำอย่างไร",
                correct=correct, wrongs=tuple(c for c in PERMISSION_CHOICES if c != correct),
                hint="ให้สิทธิ์เฉพาะที่แอปต้องใช้ทำงานตามหน้าที่ของมัน สิทธิ์ที่ไม่เกี่ยวข้องอาจถูกใช้เก็บข้อมูลของเรา",
                topic=TERMS_TOPIC,
            )
        return _labelled(
            stem="ข้อความใดมีลักษณะของการหลอกลวงทางออนไลน์",
            correct=rng.choice(SCAMS), wrongs=tuple(GENUINE),
            hint="การหลอกลวงมักเร่งให้รีบทำ ขอเงินหรือรหัสผ่าน หรือใช้ลิงก์ที่สะกดชื่อหน่วยงานผิด",
            topic=TERMS_TOPIC,
        )


