@question_type(
    "comp.search_operator_foundation",
    display_name={"th": "บอกความหมายของตัวดำเนินการค้นหา"},
    level=P6, subject=SUBJECT, topic=SEARCH_TOPIC,
)
class SearchOperatorFoundation(QuestionType):
    def build(self, rng: Random, **params):
        return _pair_either_way(rng, OPERATORS, forward="การพิมพ์คำค้นว่า {} หมายถึงข้อใด",
                                backward="ถ้าต้องการ{} ควรพิมพ์คำค้นแบบใด",
                                hint="เครื่องหมายคำพูดค้นคำที่ติดกัน เครื่องหมายลบตัดคำออก site: จำกัดเว็บไซต์ "
                                     "filetype: จำกัดชนิดไฟล์ และ OR ค้นคำใดคำหนึ่ง",
                                topic=SEARCH_TOPIC)


