def licence_failures(licence: str, use) -> list[str]:
    _, credit, commercial, adapts, same = use
    terms = LICENCES[licence]
    found = []
    if not credit:
        found.append("BY")
    if commercial and "NC" in terms:
        found.append("NC")
    if adapts and "ND" in terms:
        found.append("ND")
    if adapts and "SA" in terms and not same:
        found.append("SA")
    return found


