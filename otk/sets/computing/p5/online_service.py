def _split(rng: Random, total: int, parts: int) -> list[int]:
    """``parts`` distinct positive counts summing to ``total``, each a whole percentage of it."""
    unit = total // 20 if total % 20 == 0 else total // 10 if total % 10 == 0 else 1
    while True:
        cuts = sorted(rng.sample(range(1, total // unit), parts - 1))
        counts = [(b - a) * unit for a, b in zip([0] + cuts, cuts + [total // unit])]
        if len(set(counts)) == parts:
            return counts


