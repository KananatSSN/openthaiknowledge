@question_type(
    "comp.online_service_fluency",
    display_name={"th": "ประมวลผลคำตอบจากแบบฟอร์มออนไลน์เป็นร้อยละ"},
    level=P5, subject=SUBJECT, topic=SERVICE_TOPIC,
)
class OnlineServiceFluency(QuestionType):
    """A form's tally as a percentage of everyone who answered."""

    def build(self, rng: Random, **params):
        subject, items = rng.choice(FORM_TOPICS)
        total = rng.choice((20, 25, 40, 50, 100))
        counts = _split(rng, total, len(items))
        k = rng.randrange(len(items))
        percent = counts[k] * 100 // total
        table = " ".join(f"{i} {c} คน" for i, c in zip(items, counts))
        wrongs = _near(percent, (counts[k], 100 - percent, percent + 5, percent - 5))
        return _labelled(
            stem=(f"แบบฟอร์มออนไลน์สำรวจ{subject} มีผู้ตอบทั้งหมด {total} คน สรุปผลได้ดังนี้ {table} "
                  f"ผู้ที่เลือก{items[k]}คิดเป็นร้อยละเท่าใดของผู้ตอบทั้งหมด"),
            correct=f"ร้อยละ {percent}", wrongs=tuple(f"ร้อยละ {w}" for w in rng.sample(wrongs[:4], 3)),
            hint="ร้อยละ = จำนวนที่เลือก ÷ จำนวนผู้ตอบทั้งหมด × 100",
            topic=SERVICE_TOPIC)


