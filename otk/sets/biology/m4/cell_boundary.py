@question_type(
    "biology.cell_boundary_foundation",
    display_name={"th": "องค์ประกอบและหน้าที่ของส่วนที่ห่อหุ้มเซลล์"},
    level=UPPER_FOUR, subject=SUBJECT, topic=TOPIC_BOUNDARY,
)
class CellBoundaryFoundation(QuestionType):
    """What each boundary is made of, and what it does."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        name, made, role = rng.choice(BOUNDARY)
        others = [b for b in BOUNDARY if b[0] != name]
        if rng.random() < 0.5:
            return _labelled(stem=f"{name}มีองค์ประกอบหลักคืออะไร", correct=made, wrongs=tuple(b[1] for b in rng.sample(others, 3)),
                             topic=TOPIC_BOUNDARY, hint="เยื่อหุ้มเซลล์เป็นฟอสโฟลิพิดสองชั้น ผนังเซลล์พืชเป็นเซลลูโลส แบคทีเรียเป็นเพปทิโดไกลแคน")
        return _labelled(stem=f"{name}มีหน้าที่ใด", correct=role, wrongs=tuple(b[2] for b in rng.sample(others, 3)),
                         topic=TOPIC_BOUNDARY, hint="เยื่อหุ้มเซลล์เลือกให้สารผ่าน ผนังเซลล์ให้ความแข็งแรง")


