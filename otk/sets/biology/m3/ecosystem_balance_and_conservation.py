@question_type(
    "ecology.balance_actions_fluency",
    display_name={"th": "การกระทำที่รักษาและที่ทำลายสมดุลของระบบนิเวศ"},
    level=LEVEL, subject=SUBJECT, topic=TOPIC,
)
class BalanceActionsFluency(QuestionType):
    """Pick the one action out of four that breaks the balance, or the one that keeps it.

    Built as one-of-four rather than as a classify table on purpose: a two-category
    table would give ``ClassifyType`` only two labels to offer, and padding it to
    four would mean inventing categories that no ม.3 material names.
    """

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        if rng.random() < 0.5:
            wrongs = list(PROTECTIVE_ACTIONS)
            rng.shuffle(wrongs)
            return _labelled(
                stem="การกระทำในข้อใดทำลายสมดุลของระบบนิเวศ",
                correct=rng.choice(DAMAGING_ACTIONS),
                wrongs=tuple(wrongs[:3]),
                hint="ถามว่าการกระทำนั้นทำให้สิ่งมีชีวิตกลุ่มใดกลุ่มหนึ่งหายไป "
                     "หรือทำให้ความสัมพันธ์เดิมในระบบนิเวศเปลี่ยนไปหรือไม่",
            )
        wrongs = list(DAMAGING_ACTIONS)
        rng.shuffle(wrongs)
        return _labelled(
            stem="การกระทำในข้อใดช่วยรักษาสมดุลของระบบนิเวศ",
            correct=rng.choice(PROTECTIVE_ACTIONS),
            wrongs=tuple(wrongs[:3]),
            hint="ถามว่าการกระทำนั้นคืนสิ่งที่ถูกใช้ไปกลับสู่ระบบนิเวศ "
                 "หรือปล่อยให้สิ่งมีชีวิตมีเวลาฟื้นตัวหรือไม่",
        )


@question_type(
    "ecology.balance_application",
    display_name={"th": "ตัดสินใจโดยคำนึงถึงสมดุลของระบบนิเวศ"},
    level=LEVEL, subject=SUBJECT, topic=TOPIC,
)
class BalanceApplication(QuestionType):
    """Judge a real decision by what it does to the relationships in an ecosystem.

    ``ม.3/6`` is an awareness outcome — ``ตระหนักถึง`` — which a multiple-choice
    item cannot assess in full. What it can assess is whether a proposed action
    was chosen *because of* the relationships it affects, so every item here
    states a decision and asks which reasoning holds up.
    """

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        return contextual_scenario_question(
            rng, BALANCE_SCENARIOS,
            hint="หาให้ได้ก่อนว่าการกระทำนั้นตัดความสัมพันธ์ใดในระบบนิเวศออกไป "
                 "แล้วจึงเลือกแนวทางที่แก้ที่ความสัมพันธ์นั้น",
            topic=TOPIC,
        )
