@question_type(
    "plant.tissue_culture_fluency",
    display_name={"th": "การใช้ประโยชน์จากการเพาะเลี้ยงเนื้อเยื่อพืช"},
    level=LEVEL, subject=SUBJECT, topic=TOPIC,
)
class TissueCultureFluency(QuestionType):
    """Match a use to the property of the technique that makes it possible.

    ``ม.1/17`` asks for ``ความสำคัญ … ในการใช้ประโยชน์ด้านต่าง ๆ``, so the item
    pairs each use with the specific reason rather than with "it makes many
    plants", which would be true of every row.
    """

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        use, reason = rng.choice(TISSUE_CULTURE_USES)
        others = [other for item, other in TISSUE_CULTURE_USES if other != reason]
        rng.shuffle(others)
        if rng.random() < 0.5:
            return _labelled(
                stem=f"“{use}” ทำได้ด้วยการเพาะเลี้ยงเนื้อเยื่อเพราะเหตุใด",
                correct=reason,
                wrongs=tuple(others[:3]),
                hint="เลือกเหตุผลที่อธิบายการใช้ประโยชน์ข้อนั้นโดยเฉพาะ "
                     "ไม่ใช่ข้อดีทั่วไปที่ใช้ได้กับทุกข้อ",
            )
        wrong_uses = [item for item, other in TISSUE_CULTURE_USES if other != reason]
        rng.shuffle(wrong_uses)
        return _labelled(
            stem=f"เหตุผลที่ว่า “{reason}” อธิบายการใช้ประโยชน์ในข้อใด",
            correct=use,
            wrongs=tuple(wrong_uses[:3]),
            hint="ไล่ย้อนจากเหตุผลไปหาการใช้ประโยชน์ที่ต้องอาศัยเหตุผลนั้นโดยตรง",
        )


@question_type(
    "plant.tissue_culture_application",
    display_name={"th": "ประเมินการใช้เทคโนโลยีการเพาะเลี้ยงเนื้อเยื่อพืช"},
    level=LEVEL, subject=SUBJECT, topic=TOPIC,
)
class TissueCultureApplication(QuestionType):
    """Judge whether the technique fits a stated problem, cost included.

    Half the items are cases where it is the right answer and half are where the
    honest answer names its limits, because ``ความสำคัญ`` that never has a cost
    is a slogan rather than an understanding.
    """

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        return contextual_scenario_question(
            rng, TISSUE_CULTURE_SCENARIOS,
            hint="ถามว่าปัญหานั้นต้องการจำนวนมาก ต้องการต้นปลอดโรค "
                 "หรือต้องการความสม่ำเสมอ แล้วจึงชั่งกับต้นทุนที่ต้องจ่าย",
            topic=TOPIC,
        )
