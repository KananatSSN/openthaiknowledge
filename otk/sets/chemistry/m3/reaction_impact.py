@question_type(
    "chem.reaction_impact_foundation",
    display_name={"th": "ระบุประโยชน์และโทษของปฏิกิริยาเคมี"},
    level=SECONDARY_THREE, subject=SUBJECT, topic=IMPACT_TOPIC,
)
class ReactionImpactFoundation(QuestionType):
    """One reaction; its benefit and its harm together."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        index = rng.randrange(len(IMPACTS))
        impact = IMPACTS[index]
        first, second = rng.sample([m for i, m in enumerate(IMPACTS) if i != index], 2)

        def line(benefit: str, harm: str) -> str:
            return f"ประโยชน์: {benefit} / โทษ: {harm}"

        return _labelled(
            stem=f"ข้อใดระบุประโยชน์และโทษของ{impact.reaction}ต่อสิ่งมีชีวิตและสิ่งแวดล้อมได้ถูกต้อง",
            correct=line(impact.benefit, impact.harm),
            wrongs=(line(impact.harm, impact.benefit),
                    line(first.benefit, impact.harm),
                    line(impact.benefit, second.harm)),
            hint="ประโยชน์คือสิ่งที่คนนำปฏิกิริยาไปใช้ โทษคือความเสียหายที่ปฏิกิริยานั้นก่อ",
            topic=IMPACT_TOPIC,
        )


@question_type(
    "chem.reaction_impact_fluency",
    display_name={"th": "ยกตัวอย่างวิธีป้องกันและแก้ปัญหาที่เกิดจากปฏิกิริยาเคมี"},
    level=SECONDARY_THREE, subject=SUBJECT, topic=IMPACT_TOPIC,
)
class ReactionImpactFluency(QuestionType):
    """A problem a reaction causes; the prevention or remedy that addresses it."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        index = rng.randrange(len(IMPACTS))
        impact = IMPACTS[index]
        others = [m.remedy for i, m in enumerate(IMPACTS) if i != index]
        return _labelled(
            stem=f"{impact.problem} ซึ่งเกิดจาก{impact.reaction} ข้อใดเป็นวิธีป้องกันหรือแก้ปัญหาที่เหมาะสมที่สุด",
            correct=impact.remedy,
            wrongs=tuple(others),
            hint="หาว่าปฏิกิริยาต้องอาศัยสิ่งใด แล้วเลือกวิธีที่ตัดหรือชะลอสิ่งนั้น",
            topic=IMPACT_TOPIC,
        )


