@question_type(
    "chem.material_thrift_fluency",
    display_name={"th": "เสนอแนะแนวทางการใช้วัสดุอย่างประหยัดและคุ้มค่า"},
    level=SECONDARY_THREE, subject=SUBJECT, topic=THRIFT_TOPIC,
)
class MaterialThriftFluency(QuestionType):
    """A case; the guideline that is thrifty and worthwhile at once."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        index = rng.randrange(len(CASES))
        case = CASES[index]
        first, second = rng.sample([c for i, c in enumerate(CASES) if i != index], 2)
        return _labelled(
            stem=f"{case.case} ข้อใดเป็นแนวทางที่ทั้งประหยัดและคุ้มค่าเหมาะสมที่สุด",
            correct=_plan(case.thrifty, case.worthwhile),
            wrongs=(_plan(first.thrifty, case.worthwhile),
                    _plan(case.thrifty, first.worthwhile),
                    _plan(second.thrifty, second.worthwhile)),
            hint="ตรวจทั้งสองส่วนว่าพูดถึงวัสดุในเรื่องนี้: ส่วนที่ลดการใช้ และส่วนที่ใช้วัสดุให้เกิดประโยชน์ต่อ",
            topic=THRIFT_TOPIC,
        )


