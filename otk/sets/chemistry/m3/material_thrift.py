def fewer_items(rng: Random) -> GeneratedQuestion:
    """A daily count cut by a percentage; how many are still used."""
    thing, unit = rng.choice((("ขวดน้ำพลาสติก", "ขวด"), ("แก้วพลาสติก", "ใบ"), ("ถุงพลาสติก", "ใบ"),
                              ("กล่องโฟม", "กล่อง")))
    percent = rng.choice((20, 25, 40, 60, 75, 80))        # not 50: the cut would equal what is left
    count = rng.choice([n for n in range(100, 801, 20) if n * percent % 100 == 0])
    cut = count * percent // 100
    answer = count - cut
    pool = (cut, count, percent, count - percent, answer + percent, count + cut)
    wrongs = tuple(dict.fromkeys(f"{w} {unit}" for w in pool if w != answer and w > 0))
    return _labelled(
        stem=(f"โรงเรียนหนึ่งใช้{thing}วันละ {count} {unit} ถ้ารณรงค์ให้ใช้ภาชนะของตนเองจนใช้{thing}ลดลงร้อยละ {percent} "
              f"จะเหลือ{thing}วันละกี่{unit}"),
        correct=f"{answer} {unit}",
        wrongs=wrongs,
        hint="หาจำนวนที่ลดลงจากร้อยละก่อน แล้วลบออกจากจำนวนเดิม",
        topic=THRIFT_TOPIC,
    )


