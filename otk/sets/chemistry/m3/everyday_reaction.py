@question_type(
    "chem.everyday_reaction_foundation",
    display_name={"th": "อธิบายการเผาไหม้ ฝนกรด และการสังเคราะห์ด้วยแสงด้วยสมการข้อความจากสารสนเทศ"},
    level=SECONDARY_THREE, subject=SUBJECT, topic=EVERYDAY_TOPIC,
)
class EverydayReactionFoundation(QuestionType):
    """Three reactions known from information; all three explained with equations."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        parts = [rng.choice(variants) for variants in INFORMED_VARIANTS]
        rng.shuffle(parts)
        return parts_item(
            rng, tuple(parts),
            stem=("จากสารสนเทศเกี่ยวกับการเผาไหม้แก๊สหุงต้ม การเกิดฝนกรด และการสังเคราะห์ด้วยแสงของพืช "
                  "ข้อใดอธิบายและเขียนสมการข้อความของปฏิกิริยาทั้งสามได้ถูกต้องทั้งหมด"),
            hint="ตรวจสารตั้งต้นและผลิตภัณฑ์ของแต่ละปฏิกิริยา ข้อที่ผิดจะผิดอย่างน้อยหนึ่งปฏิกิริยา",
            topic=EVERYDAY_TOPIC,
        )


@question_type(
    "chem.everyday_reaction_fluency",
    display_name={"th": "อธิบายปฏิกิริยาของเหล็ก กรด เบส และโลหะด้วยสมการข้อความจากหลักฐาน"},
    level=SECONDARY_THREE, subject=SUBJECT, topic=EVERYDAY_TOPIC,
)
class EverydayReactionFluency(QuestionType):
    """Four experiments' observations; the word equation of every one."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        order = list(EXPERIMENTS)
        rng.shuffle(order)
        record = " / ".join(f"{e.name}: {e.seen}" for e in order)
        return parts_item(
            rng, tuple(e.equation for e in order),
            stem=(f"ผลการทดลอง 4 การทดลอง — {record} "
                  "จากหลักฐานนี้ ข้อใดเขียนสมการข้อความของปฏิกิริยาทั้งสี่ได้ถูกต้องทั้งหมด"),
            hint="แก๊สที่ติดไฟมีเสียงดังป๊อกคือแก๊สไฮโดรเจน กรดกับเบสได้เกลือกับน้ำ และสนิมต้องมีทั้งน้ำและออกซิเจน",
            topic=EVERYDAY_TOPIC,
        )


