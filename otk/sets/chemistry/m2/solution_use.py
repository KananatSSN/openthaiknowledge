def mix_ratio(rng: Random) -> GeneratedQuestion:
    """A label's 1 : k mix; how much concentrate a stated total needs."""
    k = rng.choice((3, 4, 9, 19))
    part = rng.choice((20, 25, 50, 100))
    total = (k + 1) * part
    pool = [total - part, total, 2 * part, total // 2]
    if total % k == 0:
        pool.append(total // k)
    wrongs = tuple(dict.fromkeys(f"{w} ลูกบาศก์เซนติเมตร" for w in pool if w != part))
    return _labelled(
        stem=(f"ฉลากน้ำยาถูพื้นระบุให้ผสมน้ำยา 1 ส่วนต่อน้ำ {k} ส่วน ถ้าต้องการน้ำยาที่ผสมแล้วทั้งหมด "
              f"{total} ลูกบาศก์เซนติเมตร ต้องใช้น้ำยากี่ลูกบาศก์เซนติเมตร"),
        correct=f"{part} ลูกบาศก์เซนติเมตร",
        wrongs=wrongs,
        hint="น้ำยา 1 ส่วนกับน้ำ k ส่วนรวมเป็น k + 1 ส่วน จึงหารปริมาตรทั้งหมดด้วย k + 1",
        topic=SOLUTION_USE_TOPIC,
    )


