@question_type(
    "chem.atom_element_compound_fluency",
    display_name={"th": "อะตอม ธาตุ และสารประกอบ: อ่านสูตรและแบบจำลอง"},
    level={"th": "ม.1"}, subject=CHEMISTRY, topic=MATTER,
)
class AtomElementCompoundFluency(QuestionType):
    """Read one chemical formula as a model of what the substance is made of."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        which = rng.randrange(2)
        if which == 0:
            formula, name, first, second, (element_a, element_b) = rng.choice(
                [item for item in FORMULA_FACTS if item[2] != item[3]]
            )
            total = first + second
            return _question(
                stem=f"สูตรเคมี {formula} ของ{name} บอกอะไรเกี่ยวกับหนึ่งโมเลกุลของสารนี้",
                correct=(f"หนึ่งโมเลกุลมีอะตอม{element_a} {first} อะตอม "
                         f"และอะตอม{element_b} {second} อะตอม"),
                wrongs=(
                    (f"หนึ่งโมเลกุลมีอะตอม{element_a} {second} อะตอม "
                     f"และอะตอม{element_b} {first} อะตอม"),
                    f"หนึ่งโมเลกุลมีอะตอมทั้งหมด {total} ชนิดที่ต่างกัน",
                    f"หนึ่งโมเลกุลมีธาตุ {total} ธาตุผสมกันอยู่โดยไม่รวมตัวทางเคมี",
                    f"หนึ่งโมเลกุลมีอะตอม{element_a} {total} อะตอม และไม่มีอะตอม{element_b}",
                    f"หนึ่งโมเลกุลมีอะตอม{element_a}และอะตอม{element_b}อย่างละ {total} อะตอม",
                ),
                hint="ตัวเลขห้อยท้ายบอกจำนวนอะตอมของธาตุที่อยู่ข้างหน้า ไม่ใช่จำนวนชนิดของธาตุ",
                topic=MATTER,
            )
        formula, kind, reason = rng.choice(ELEMENT_OR_COMPOUND)
        other = "สารประกอบ" if kind == "ธาตุ" else "ธาตุ"
        other_reason = next(r for _, k, r in ELEMENT_OR_COMPOUND if k == other)
        return _question(
            stem=f"สาร {formula} จัดเป็นธาตุหรือสารประกอบ และเพราะเหตุใด",
            correct=f"{kind} เพราะ{reason}",
            wrongs=(
                f"{other} เพราะ{other_reason}",
                f"{other} เพราะ{reason}",
                f"{kind} เพราะเป็นสารผสมของอะตอมหลายชนิดที่แยกออกจากกันได้ด้วยวิธีทางกายภาพ",
                f"{other} เพราะเป็นสารผสมที่แยกได้ด้วยการกรอง",
                f"{kind} เพราะมีสถานะเป็นแก๊สที่อุณหภูมิห้อง",
            ),
            hint="ดูว่าสูตรมีสัญลักษณ์ธาตุกี่ชนิด ชนิดเดียวคือธาตุ มากกว่าหนึ่งชนิดคือสารประกอบ",
            topic=MATTER,
        )


