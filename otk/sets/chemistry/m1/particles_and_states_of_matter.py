@question_type(
    "chem.particle_state_fluency",
    display_name={"th": "อนุภาคและสถานะของสสาร: เปรียบเทียบแบบจำลองอนุภาค"},
    level={"th": "ม.1"}, subject=CHEMISTRY, topic=MATTER,
)
class ParticleStateFluency(QuestionType):
    """Compare arrangement, force, or motion between two states."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        which = rng.randrange(3)
        state, arrangement, force, motion = rng.choice(STATE_MODELS)
        others = [item for item in STATE_MODELS if item[0] != state]
        if which == 0:
            wrongs = _distinct(arrangement, [item[1] for item in others] + [
                "อนุภาคหายไปจนไม่เหลืออยู่ในภาชนะ",
                "อนุภาคซ้อนทับกันจนกลายเป็นอนุภาคเดียว",
                "อนุภาคเรียงเป็นชั้นตามสีของสาร",
            ], want=5)
            assert wrongs is not None
            return _question(
                stem=f"ในแบบจำลองอนุภาค สสารสถานะ{state}มีการจัดเรียงอนุภาคอย่างไร",
                correct=arrangement,
                wrongs=wrongs,
                hint="เรียงลำดับความชิดของอนุภาคจากของแข็ง ของเหลว ไปแก๊ส",
            )
        if which == 1:
            wrongs = _distinct(motion, [item[3] for item in others] + [
                "หยุดนิ่งสนิทโดยไม่มีการเคลื่อนไหวใด ๆ",
                "เคลื่อนที่เฉพาะเมื่อมีลมพัดผ่านเท่านั้น",
                "หมุนรอบตัวเองอยู่กับที่โดยไม่สั่นเลย",
            ], want=5)
            assert wrongs is not None
            return _question(
                stem=f"อนุภาคของสสารสถานะ{state}มีการเคลื่อนที่อย่างไร",
                correct=motion,
                wrongs=wrongs,
                hint="ยิ่งแรงยึดเหนี่ยวระหว่างอนุภาคน้อย อนุภาคยิ่งเคลื่อนที่ได้อิสระมากขึ้น",
            )
        wrongs = _distinct(force, [item[2] for item in others] + [
            "ไม่มีแรงยึดเหนี่ยวระหว่างอนุภาคเลยในทุกสถานะ",
            "แรงยึดเหนี่ยวเท่ากันในทุกสถานะ",
            "แรงยึดเหนี่ยวขึ้นกับสีของสารเท่านั้น",
        ], want=5)
        assert wrongs is not None
        return _question(
            stem=f"แรงยึดเหนี่ยวระหว่างอนุภาคของสสารสถานะ{state}เป็นอย่างไรเมื่อเทียบกับสถานะอื่น",
            correct=force,
            wrongs=wrongs,
            hint="แรงยึดเหนี่ยวมากทำให้อนุภาคอยู่ชิดกันและเคลื่อนที่ได้น้อย",
        )


