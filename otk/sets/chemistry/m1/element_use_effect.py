@question_type(
    "chem.element_use_effect_foundation",
    display_name={"th": "ระบุประเภทของธาตุจากการใช้ประโยชน์"},
    level=SECONDARY_ONE, subject=SUBJECT, topic=EFFECTS_TOPIC,
)
class ElementUseEffectFoundation(QuestionType):
    """A use; which element serves it, and its class."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        index = rng.randrange(len(USES))
        use = USES[index]
        others = [u for i, u in enumerate(USES) if i != index]
        return _labelled(
            stem=f"ธาตุใดใช้{use.use} และจัดเป็นธาตุประเภทใด",
            correct=f"{use.element} เป็น{use.kind}",
            wrongs=tuple(f"{u.element} เป็น{u.kind}" for u in rng.sample(others, 3)),
            hint="นึกถึงสมบัติที่การใช้งานนั้นต้องการ แล้วจับคู่กับธาตุที่มีสมบัตินั้น",
            topic=EFFECTS_TOPIC,
        )


@question_type(
    "chem.element_use_effect_fluency",
    display_name={"th": "วิเคราะห์ผลจากการใช้ธาตุจากข้อมูลที่รวบรวมได้"},
    level=SECONDARY_ONE, subject=SUBJECT, topic=EFFECTS_TOPIC,
)
class ElementUseEffectFluency(QuestionType):
    """Collected data on one use; analyse the effects on all three together."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        use = rng.choice(USES)
        effects = tuple(Part(part.label, part.true, rng.choice((part.false, slip)))
                        for part, slip in zip(use.effects, use.slips))
        return parts_item(
            rng, effects,
            stem=(f"ข้อมูลที่รวบรวมได้เกี่ยวกับการใช้{use.element} ({use.kind}) {use.use} — {use.data} "
                  "จากข้อมูลนี้ ข้อใดวิเคราะห์ผลต่อสิ่งมีชีวิต สิ่งแวดล้อม และเศรษฐกิจและสังคมได้ถูกต้องทั้งหมด"),
            hint="ตรวจทีละด้านกับข้อมูลที่ให้มา ข้อที่ผิดจะวิเคราะห์ผิดอย่างน้อยหนึ่งด้าน",
            topic=EFFECTS_TOPIC,
        )


