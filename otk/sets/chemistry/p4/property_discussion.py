@question_type(
    "chem.property_discussion_foundation",
    display_name={"th": "เลือกเหตุผลที่อ้างอิงผลการทดลอง"},
    level=FOURTH, subject=SUBJECT, topic=DISCUSSION_TOPIC,
)
class PropertyDiscussionFoundation(QuestionType):
    """Which of four statements is a reason drawn from the experiment."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        claim = rng.choice(CLAIMS)
        return _labelled(
            stem=f"ผลการทดลองคือ {claim.result} ข้อใดเป็นการให้เหตุผลที่อ้างอิงผลการทดลองนี้",
            correct=_reason(claim.response),
            wrongs=tuple(_reason(wrong) for wrong in claim.wrongs),
            hint="เหตุผลที่ดีต้องพูดถึงสิ่งที่เห็นในการทดลอง ไม่ใช่ความรู้สึกหรือลักษณะที่ไม่เกี่ยวข้อง",
            topic=DISCUSSION_TOPIC,
        )


@question_type(
    "chem.property_discussion_fluency",
    display_name={"th": "ตอบข้อกล่าวอ้างของเพื่อนอย่างมีเหตุผลจากผลการทดลอง"},
    level=FOURTH, subject=SUBJECT, topic=DISCUSSION_TOPIC,
)
class PropertyDiscussionFluency(QuestionType):
    """A result and a friend's claim; the response that agrees or disagrees with reason."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        claim = rng.choice(CLAIMS)
        return _labelled(
            stem=(f"ขณะอภิปรายในกลุ่ม ผลการทดลองคือ {claim.result} เพื่อนคนหนึ่งกล่าวว่า "
                  f"\"{claim.claim}\" ข้อใดเป็นการตอบเพื่อนที่มีเหตุผลที่สุด"),
            correct=claim.response,
            wrongs=claim.wrongs,
            hint="ตัดสินว่าเห็นด้วยหรือไม่จากผลการทดลอง แล้วบอกว่าผลข้อใดสนับสนุน",
            topic=DISCUSSION_TOPIC,
        )


@question_type(
    "chem.property_discussion_application",
    display_name={"th": "ใช้การอภิปรายอย่างมีเหตุผลแก้ข้อขัดแย้งของผลการทดลอง"},
    level=FOURTH, subject=SUBJECT, topic=DISCUSSION_TOPIC,
)
class PropertyDiscussionApplication(QuestionType):
    """Two groups disagreeing, listening to a different result, and a hasty generalisation."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        return _retopic(scenario_question(
            rng, DISCUSSION_SCENARIOS,
            hint="การอภิปรายที่มีเหตุผลอ้างอิงหลักฐาน ฟังผู้อื่น และตรวจว่าการทดลองยุติธรรมพอหรือไม่",
        ), DISCUSSION_TOPIC)
