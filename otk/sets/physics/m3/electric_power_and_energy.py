@question_type("elec.power",
               display_name={"th": "กำลังไฟฟ้า (P = VI)"},
               level=LEVEL, subject=SUBJECT, topic=TOPIC)
class Power(PhysCalc):
    """P = VI — ถามครบทั้งสามทาง ตามตัวอย่างที่ 2 และ 3 ในชีท."""

    # ความต่างศักย์คู่กับเครื่องใช้ไฟฟ้าที่ใช้แรงดันนั้นจริง ๆ — ไม่มีเตารีด 6 โวลต์
    _SOURCES = [
        (220, ("ตู้เย็น", "เครื่องสูบน้ำ", "หม้อหุงข้าว", "เตารีด", "เครื่องปรับอากาศ")),
        (110, ("พัดลม", "โทรทัศน์", "เครื่องดูดฝุ่น")),
        (12, ("ปั๊มลมขนาดเล็ก", "เครื่องเล่นเพลงในรถ")),
        (6, ("วิทยุขนาดเล็ก", "พัดลมพกพา")),
    ]
    _I = [0.5, 1.5, 2, 2.5, 3, 4, 5]         # กระแสไฟฟ้า (แอมแปร์)

    def draw(self, rng: Random) -> Calc:
        v, things = rng.choice(self._SOURCES)
        i = rng.choice(self._I)
        p = v * i
        thing = rng.choice(things)
        which = rng.random()
        if which < 0.4:                      # ให้ V กับ I → หา P
            return Calc(
                f"วัดกระแสไฟฟ้าที่ผ่าน{thing}เครื่องหนึ่งได้ {fmt(i)} แอมแปร์ "
                f"เมื่อต่อกับความต่างศักย์ {v} โวลต์ "
                f"เครื่องนี้ใช้กำลังไฟฟ้าเท่าใด (วัตต์)",
                fmt(p), wrongs=slips(fmt(p), v + i, v / i, p * 2),
                hint=r"P = VI")
        if which < 0.75:                     # ให้ P กับ V → หา I
            return Calc(
                f"{thing}เครื่องหนึ่งใช้กำลังไฟฟ้า {fmt(p)} วัตต์ "
                f"ที่ความต่างศักย์ {v} โวลต์ มีกระแสไฟฟ้าผ่านเท่าใด (แอมแปร์)",
                fmt(i), wrongs=slips(fmt(i), v / p, p - v, p / (v * 2)),
                hint=r"I = \frac{P}{V}")
        return Calc(                         # ให้ P กับ I → หา V
            f"{thing}เครื่องหนึ่งใช้กำลังไฟฟ้า {fmt(p)} วัตต์ "
            f"ขณะที่มีกระแสไฟฟ้าผ่าน {fmt(i)} แอมแปร์ "
            f"จงหาความต่างศักย์ที่ใช้กับเครื่องนี้ (โวลต์)",
            fmt(v), wrongs=slips(fmt(v), p * i, i / p, p - i),
            hint=r"V = \frac{P}{I}")


@question_type(
    "elec.energy_power_time",
    display_name={"th": "พลังงานไฟฟ้าจากกำลังและเวลา (W = Pt)"},
    level={"th": "ม.3"}, subject="ฟิสิกส์", topic="ไฟฟ้า",
)
class EnergyPowerTime(_PinnedEnergy):
    source_key = "elec.energy"

    def draw(self, rng: Random) -> Calc:
        which = rng.randrange(3)
        if which == 0:
            power, minutes = rng.choice(self._P), rng.choice(self._MIN)
            energy = power * minutes * 60
            return Calc(
                f"หลอดไฟฟ้าขนาด {power} วัตต์ เปิดใช้งานนาน {minutes} นาที "
                f"สิ้นเปลืองพลังงานไฟฟ้าไปเท่าใด (จูล)",
                fmt(energy),
                wrongs=slips(fmt(energy), power * minutes, power * 60, minutes * 60),
                hint=r"W = Pt",
            )
        power, seconds = rng.choice(self._P), rng.choice(self._SEC)
        energy = power * seconds
        if which == 1:
            return Calc(
                f"เครื่องใช้ไฟฟ้าขนาด {power} วัตต์ ทำงานนาน {seconds} วินาที "
                f"ใช้พลังงานไฟฟ้าไปเท่าใด (จูล)",
                fmt(energy),
                wrongs=slips(fmt(energy), power * seconds / 60, power + seconds, power * 60),
                hint=r"W = Pt",
            )
        return Calc(
            f"เครื่องใช้ไฟฟ้าเครื่องหนึ่งใช้พลังงานไฟฟ้า {energy} จูล "
            f"ในเวลา {seconds} วินาที เครื่องนี้ใช้กำลังไฟฟ้าเท่าใด (วัตต์)",
            fmt(power),
            wrongs=slips(fmt(power), energy * 60 / seconds, energy / 60, seconds),
            hint=r"P = \frac{W}{t}",
        )


@question_type("elec.electricity_bill",
               display_name={"th": "หน่วยไฟฟ้าและค่าไฟ (กิโลวัตต์·ชั่วโมง)"},
               level=LEVEL, subject=SUBJECT, topic=TOPIC)
class ElectricityBill(PhysCalc):
    """หน่วยไฟฟ้า = กิโลวัตต์ × ชั่วโมง แล้วคูณด้วยราคาต่อหน่วยเป็นค่าไฟ.

    นี่คือ W = Pt ในหน่วยที่ใบเสร็จค่าไฟใช้จริง กับดักคือกำลังไฟฟ้าบนฉลากเป็น
    *วัตต์* แต่หน่วยไฟฟ้าคิดเป็น *กิโลวัตต์* — คำตอบที่ลืมหารด้วย 1,000
    จึงถูกเสนอเป็นตัวเลือกเสมอ.
    """

    _P = [60, 100, 500, 1000, 1500, 2000]    # กำลังไฟฟ้าบนฉลาก (วัตต์)
    _HOURS = [1, 2, 4, 5]                    # ชั่วโมงต่อวัน
    _DAYS = [10, 20, 30]                     # จำนวนวัน
    _RATE = [4, 5]                           # ราคาต่อหน่วย (บาท)
    _APPLIANCE = ["เครื่องปรับอากาศ", "เครื่องทำน้ำอุ่น", "เตารีด", "โทรทัศน์",
                  "หม้อหุงข้าว"]

    def draw(self, rng: Random) -> Calc:
        p = rng.choice(self._P)
        hours, days = rng.choice(self._HOURS), rng.choice(self._DAYS)
        thing = rng.choice(self._APPLIANCE)
        units = p / 1000 * hours * days
        which = rng.random()
        if which < 0.4:                      # หาจำนวนหน่วยไฟฟ้า
            return Calc(
                f"{thing}ขนาด {p} วัตต์ เปิดใช้งานวันละ {hours} ชั่วโมง "
                f"เป็นเวลา {days} วัน จะใช้ไฟฟ้าไปกี่หน่วย (กิโลวัตต์·ชั่วโมง)",
                fmt(units), wrongs=slips(fmt(units), p * hours * days,
                                         p / 1000 * hours, p / 1000 * days),
                hint=r"E = \frac{P}{1000} \times t")
        if which < 0.8:                      # หาค่าไฟเป็นบาท
            rate = rng.choice(self._RATE)
            return Calc(
                f"{thing}ขนาด {p} วัตต์ เปิดใช้งานวันละ {hours} ชั่วโมง "
                f"เป็นเวลา {days} วัน ถ้าค่าไฟฟ้าหน่วยละ {rate} บาท "
                f"จะต้องจ่ายค่าไฟฟ้าเท่าใด (บาท)",
                fmt(units * rate), wrongs=slips(fmt(units * rate), units,
                                                p * hours * days * rate,
                                                units / rate),
                hint=r"C = \frac{P}{1000} \times t \times r")
        return Calc(                         # ให้จำนวนหน่วย → หากำลังไฟฟ้า
            f"{thing}เครื่องหนึ่งเปิดใช้งานวันละ {hours} ชั่วโมง เป็นเวลา {days} วัน "
            f"แล้วใช้ไฟฟ้าไป {fmt(units)} หน่วย เครื่องนี้มีกำลังไฟฟ้ากี่วัตต์",
            fmt(p), wrongs=slips(fmt(p), units / (hours * days),
                                 units * hours * days, p / 1000),
            hint=r"P = \frac{1000E}{t}")
