            correct=problem.method,
            wrongs=tuple(others),
            hint="แยกพิจารณาว่าปัญหาเป็นเรื่องความสิ้นเปลืองพลังงานหรือความปลอดภัย แล้วเลือกวิธีที่ตรงจุด",
