            wrongs=("เลนส์แก้วตาโค้งน้อยลงเมื่อมองวัตถุใกล้ และโค้งมากขึ้นเมื่อมองวัตถุไกล",
                    "เลนส์แก้วตามีความโค้งคงที่เสมอไม่ว่าจะมองวัตถุใกล้หรือไกล",
                    "ภาพที่เกิดบนจอตาไม่เกี่ยวข้องกับความโค้งของเลนส์แก้วตาเลย"),
