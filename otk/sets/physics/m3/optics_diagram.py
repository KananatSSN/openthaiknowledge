LENS_CASES = (
    # (object position rule, image, device)
    ("far", "ภาพจริง หัวกลับ ขนาดเล็กกว่าวัตถุ", "กล้องถ่ายรูป"),
    ("twice", "ภาพจริง หัวกลับ ขนาดเท่าวัตถุ", "เครื่องถ่ายเอกสารที่ย่อขยายเท่าเดิม"),
    ("between", "ภาพจริง หัวกลับ ขนาดใหญ่กว่าวัตถุ", "เครื่องฉายภาพ"),
    ("inside", "ภาพเสมือน หัวตั้ง ขนาดใหญ่กว่าวัตถุ", "แว่นขยาย"),
)


def lens_distance(rng: Random, rule: str, focal: int) -> int:
    """An object distance in whole centimetres that falls in ``rule``'s zone."""
    return {"far": rng.randint(2 * focal + 1, 4 * focal), "twice": 2 * focal,
            "between": rng.randint(focal + 1, 2 * focal - 1), "inside": rng.randint(max(2, focal // 3), focal - 1)}[rule]


