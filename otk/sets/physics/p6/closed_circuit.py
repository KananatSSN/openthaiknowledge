class ClosedCircuitApplication(QuestionType):
    """Authored cases, and a broken loop in a named device with the fix."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        if rng.random() < 0.65:
            device = rng.choice(("ไฟฉาย", "รถของเล่นใช้ถ่าน", "กริ่งประตูใช้ถ่าน", "นาฬิกาปลุกใช้ถ่าน", "โคมไฟตั้งโต๊ะใช้ถ่าน"))
            cause, fix = rng.choice(DEVICE_FAULTS)
            return _labelled(
                stem=f"{device}ไม่ทำงานทั้งที่ถ่านยังใหม่ เมื่อตรวจดูพบว่า{cause} ควรแก้อย่างไร",
                correct=fix,
                wrongs=tuple([f for c, f in DEVICE_FAULTS if f != fix] + list(WRONG_FIXES)),
                hint="ถามก่อนเสมอว่าทางเดินของกระแสไฟฟ้าขาดที่ใด แล้วแก้ตรงจุดนั้นให้วงจรครบรอบ",
                topic=CLOSED_CIRCUIT_TOPIC,
            )
        return _retopic(scenario_question(
            rng, CLOSED_CIRCUIT_SCENARIOS,
            hint=("ถามก่อนเสมอว่าทางเดินของกระแสไฟฟ้าครบรอบหรือไม่ "
                  "แล้วจึงค่อยสงสัยว่าอุปกรณ์ชิ้นใดเสีย"),
        ), CLOSED_CIRCUIT_TOPIC)
