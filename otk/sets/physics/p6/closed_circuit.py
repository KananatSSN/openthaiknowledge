    """One thing observed about the loop; whether current can go round it."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        observation, correct = PATH_CASES[rng.randrange(len(PATH_CASES))]
        wrongs = (
            "วงจรปิด กระแสไฟฟ้าไหลครบรอบได้ หลอดไฟจึงสว่าง"
            if correct.startswith("วงจรเปิด") else
            "วงจรเปิด กระแสไฟฟ้าไหลครบรอบไม่ได้ หลอดไฟจึงไม่สว่าง",
            "วงจรปิด แต่กระแสไฟฟ้าไหลได้เพียงครึ่งรอบ หลอดไฟจึงสว่างเพียงครึ่งเดียว",
            "เป็นวงจรปิดหรือวงจรเปิดก็ได้ เพราะสิ่งที่สังเกตได้ไม่เกี่ยวกับทางเดินของกระแสไฟฟ้า",
        )
        return _labelled(
            stem=f"{rng.choice(('นักเรียน', 'เพื่อน', 'ครู'))}ต่อวงจรไฟฟ้าอย่างง่ายที่มีหลอดไฟแล้วสังเกตว่า {observation} วงจรนี้เป็นอย่างไร",
            correct=correct,
            wrongs=wrongs,
            hint="ลองไล่ทางเดินของกระแสไฟฟ้าจากขั้วหนึ่งของเซลล์ไฟฟ้าไปจนกลับถึงอีกขั้วหนึ่ง",
            topic=CLOSED_CIRCUIT_TOPIC,
        )


