@question_type(
    "phys.parallel_bulbs_benefit_fluency",
    display_name={"th": "บอกประโยชน์ ข้อจำกัด และการประยุกต์ใช้การต่อหลอดไฟฟ้าในชีวิตประจำวัน"},
    level=SIXTH, subject=SUBJECT, topic=PARALLEL_BULBS_BENEFIT_TOPIC,
)
class ParallelBulbsBenefitFluency(QuestionType):
    """A real device; the benefit or limitation of how its bulbs are connected."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        index = rng.randrange(len(BULB_USES))
        use = BULB_USES[index]
        others = [u.trait for i, u in enumerate(BULB_USES) if i != index]
        return _labelled(
            stem=f"{use.device} มีประโยชน์และข้อจำกัดอย่างไร",
            correct=use.trait,
            wrongs=tuple(others),
            hint="เปรียบเทียบว่าการต่อแบบนั้นทำให้แต่ละหลอดเป็นอิสระต่อกันหรือไม่ เมื่อหลอดหนึ่งเสีย",
            topic=PARALLEL_BULBS_BENEFIT_TOPIC,
        )


