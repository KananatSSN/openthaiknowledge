@question_type(
    "phys.parallel_bulbs_fluency",
    display_name={"th": "ทดลองอธิบายผลของการต่อหลอดไฟฟ้าแบบอนุกรมและแบบขนาน"},
    level=SIXTH, subject=SUBJECT, topic=PARALLEL_BULBS_TOPIC,
)
class ParallelBulbsFluency(QuestionType):
    """The two-circuit experiment, or n bulbs with one taken out."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        if rng.random() < 0.2:
            return _labelled(
                stem=("นักเรียนต่อวงจรหลอดไฟฟ้า 2 ดวงสองแบบ วงจรที่ 1 ต่อแบบอนุกรม เมื่อถอดหลอดหนึ่งออก หลอดอีกดวงดับไปด้วย "
                      "วงจรที่ 2 ต่อแบบขนาน เมื่อถอดหลอดหนึ่งออก หลอดอีกดวงยังคงสว่างตามปกติ "
                      "จากผลการทดลองนี้ ข้อใดอธิบายการต่อหลอดไฟฟ้าทั้งสองแบบได้ถูกต้อง"),
                correct=("วงจรอนุกรมมีเส้นทางเดียว ถอดหลอดหนึ่งออกวงจรจึงขาด หลอดอื่นดับไปด้วย "
                         "ส่วนวงจรขนานมีหลายเส้นทางแยกจากกัน ถอดหลอดหนึ่งออกหลอดอื่นจึงยังสว่างได้"),
                wrongs=("วงจรอนุกรมมีหลายเส้นทาง ถอดหลอดหนึ่งออกหลอดอื่นจึงยังสว่างได้ ส่วนวงจรขนานมีเส้นทางเดียว ถอดหลอดหนึ่งออกวงจรจึงขาด",
                        "ทั้งวงจรอนุกรมและวงจรขนานจะดับทั้งหมดเมื่อถอดหลอดใดหลอดหนึ่งออก",
                        "การถอดหลอดไฟฟ้าออกไม่มีผลต่อวงจรไม่ว่าจะต่อแบบใด"),
                hint=BULB_HINT, topic=PARALLEL_BULBS_TOPIC,
            )
        count = rng.randint(2, 6)
        removed = rng.randint(1, count)
        series = rng.random() < 0.5
        lit = 0 if series else count - 1
        options = sorted({0, count - 1, count, 1 if count > 2 else 2, count - 2 if count > 2 else 3})
        wrongs = [f"{n} ดวง" for n in options if n != lit][:3]
        return _labelled(stem=f"ต่อหลอดไฟฟ้า {count} ดวงแบบ{'อนุกรม' if series else 'ขนาน'}กับถ่านไฟฉาย ทุกดวงสว่าง "
                              f"ถ้าถอดหลอดดวงที่ {removed} ออก จะเหลือหลอดที่ยังสว่างกี่ดวง",
                         correct=f"{lit} ดวง", wrongs=tuple(wrongs), hint=BULB_HINT, topic=PARALLEL_BULBS_TOPIC)


@question_type(
    "phys.parallel_bulbs_application",
    display_name={"th": "ประเมินการเลือกต่อหลอดไฟฟ้าแบบอนุกรมหรือแบบขนานในอุปกรณ์จริง"},
    level=SIXTH, subject=SUBJECT, topic=PARALLEL_BULBS_TOPIC,
)
class ParallelBulbsApplication(QuestionType):
    """Authored devices, and two students' circuits compared by brightness."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        if rng.random() < 0.3:
            return _retopic(scenario_question(
                rng, PARALLEL_BULBS_SCENARIOS,
                hint="การต่อแบบขนานให้แต่ละหลอดทำงานอิสระ เหมาะกับงานที่ต้องการความเชื่อถือได้",
            ), PARALLEL_BULBS_TOPIC)
        a, b = rng.sample(("ต้น", "ฝน", "มะลิ", "ภูมิ", "ข้าวหอม", "ปลา"), 2)
        na, nb = rng.randint(2, 5), rng.randint(2, 5)
        return _labelled(stem=f"{a}ต่อหลอดไฟฟ้า {na} ดวงแบบอนุกรม {b}ต่อหลอดไฟฟ้าชนิดเดียวกัน {nb} ดวงแบบขนาน ใช้ถ่านไฟฉายชุดเดียวกัน "
                              f"หลอดของใครแต่ละดวงสว่างกว่า",
                         correct=f"หลอดของ{b} เพราะต่อแบบขนาน แต่ละดวงได้รับไฟฟ้าเต็มที่",
                         wrongs=(f"หลอดของ{a} เพราะต่อแบบอนุกรม แต่ละดวงได้รับไฟฟ้าเต็มที่", "สว่างเท่ากัน เพราะใช้ถ่านชุดเดียวกัน",
                                 f"หลอดของ{a} เพราะหลอดที่ต่อเรียงกันช่วยกันสว่าง"),
                         hint="หลอดที่ต่อแบบอนุกรมแบ่งกันใช้ไฟฟ้า จึงสว่างน้อยลง ส่วนแบบขนานแต่ละดวงสว่างใกล้เคียงหลอดเดียว",
                         topic=PARALLEL_BULBS_TOPIC)
