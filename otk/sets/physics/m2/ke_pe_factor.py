@question_type(
    "phys.ke_pe_factor_fluency",
    display_name={"th": "ออกแบบและทดลองอธิบายปัจจัยที่มีผลต่อพลังงานจลน์และพลังงานศักย์"},
    level=SECOND_SECONDARY, subject=SUBJECT, topic=KE_PE_FACTOR_TOPIC,
)
class KePeFactorFluency(QuestionType):
    """The three-experiment summary, or one experiment's drawn results."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        if rng.random() < 0.25:
            return parts_item(rng, KE_PE_PARTS, stem=KE_PE_PARTS_STEM,
                              hint="แยกพิจารณาแต่ละชุดการทดลอง: ชุดใดเปลี่ยนมวล ชุดใดเปลี่ยนอัตราเร็ว และชุดใดเปลี่ยนความสูง",
                              topic=KE_PE_FACTOR_TOPIC)
        setup, varied, measured, right, wrongs = rng.choice(EXPERIMENTS)
        fixed = rng.choice((50, 100, 200)) if "กรัม" in setup else rng.choice((20, 30, 40, 50)) if "cm" in setup else rng.choice((1, 2, 3))
        start, step = rng.choice({"ความสูง (cm)": ((10, 10), (20, 10), (20, 20), (30, 10)), "มวล (g)": ((50, 50), (100, 50), (100, 100)),
                                  "อัตราเร็ว (m/s)": ((1, 1), (2, 1), (1, 2))}[varied])
        xs = [start + step * i for i in range(3)]
        base, grow = rng.randint(3, 12), rng.randint(3, 10)
        ys = [base + grow * i for i in range(3)]
        table = " ".join(f"{varied} {x} → {measured} {y}" for x, y in zip(xs, ys))
        return _labelled(stem=f"นักเรียน{setup.format(fixed=fixed)} ได้ผลดังนี้: {table} ข้อสรุปใดถูกต้อง", correct=right, wrongs=wrongs,
                         hint="ดูว่าตัวแปรต้นที่เปลี่ยนคืออะไร และผลที่วัดได้เพิ่มหรือลดตามตัวแปรนั้น", topic=KE_PE_FACTOR_TOPIC)


@question_type(
    "phys.ke_pe_factor_application",
    display_name={"th": "เปรียบเทียบพลังงานจลน์และพลังงานศักย์โน้มถ่วงในสถานการณ์จริง"},
    level=SECOND_SECONDARY, subject=SUBJECT, topic=KE_PE_FACTOR_TOPIC,
)
class KePeFactorApplication(QuestionType):
    """Authored comparisons, and the largest Ek or Ep among four drawn objects."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        roll = rng.random()
        if roll < 0.2:
            return _retopic(scenario_question(
                rng, KE_PE_SCENARIOS,
                hint="พลังงานจลน์เพิ่มตามมวลและอัตราเร็ว พลังงานศักย์โน้มถ่วงเพิ่มตามมวลและความสูง",
            ), KE_PE_FACTOR_TOPIC)
        kinetic = roll < 0.6
        while True:
            pairs = [(rng.randint(1, 10), rng.randint(1, 10)) for _ in NAMES]
            values = [Fraction(m * v * v, 2) if kinetic else 10 * m * v for m, v in pairs]
            if values.count(max(values)) == 1 and len(set(pairs)) == 4:
                break
        pick = values.index(max(values))
        if kinetic:
            table = " ".join(f"วัตถุ {n} มวล {m} kg อัตราเร็ว {v} m/s" for n, (m, v) in zip(NAMES, pairs))
            stem = f"{table} วัตถุใดมีพลังงานจลน์มากที่สุด (Ek = ½mv²)"
        else:
            table = " ".join(f"วัตถุ {n} มวล {m} kg อยู่สูง {h} m" for n, (m, h) in zip(NAMES, pairs))
            stem = f"{table} วัตถุใดมีพลังงานศักย์โน้มถ่วงมากที่สุด (Ep = mgh, g = 10 N/kg)"
        return _labelled(stem=stem, correct=f"วัตถุ {NAMES[pick]}", wrongs=tuple(f"วัตถุ {n}" for n in NAMES if n != NAMES[pick]),
                         hint=KE_PE_HINT + " คำนวณของแต่ละวัตถุแล้วเปรียบเทียบ", topic=KE_PE_FACTOR_TOPIC)
