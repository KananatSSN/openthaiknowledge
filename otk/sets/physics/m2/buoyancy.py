@question_type(
    "phys.buoyancy_foundation",
    display_name={"th": "บอกเงื่อนไขการจมและการลอยของวัตถุ"},
    level=SECONDARY_TWO, subject=SUBJECT, topic=BUOYANCY_TOPIC,
)
class BuoyancyFoundation(QuestionType):
    """When an object floats or sinks, in general or for a given weight and buoyant force."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        roll = rng.random()
        if roll < 0.3:
            return _facts(rng, BUOYANCY_FACTS, hint=BUOYANCY_HINT, topic=BUOYANCY_TOPIC)
        if roll < 0.75:
            thing = rng.choice(("วัตถุ ก", "กล่องปิดสนิท", "ขวดปิดฝาที่ใส่ทรายไว้บางส่วน", "ลูกบอล", "กระป๋องปิดฝา", "ทุ่นพลาสติก"))
            weight = rng.randint(3, 20)
            buoyant = rng.choice([b for b in range(1, 26) if b != weight])
            floats = buoyant > weight
            return _labelled(
                stem=(f"{thing}หนัก {weight} นิวตัน เมื่อกดให้จมมิดน้ำจะได้แรงพยุง {buoyant} นิวตัน "
                      f"ถ้าปล่อย{thing}ใต้น้ำ จะเป็นอย่างไร"),
                correct=("ลอยขึ้น เพราะแรงพยุงมากกว่าน้ำหนัก" if floats else "จมลง เพราะน้ำหนักมากกว่าแรงพยุง"),
                wrongs=(("จมลง เพราะน้ำหนักมากกว่าแรงพยุง" if floats else "ลอยขึ้น เพราะแรงพยุงมากกว่าน้ำหนัก"),
                        ("ลอยขึ้น เพราะน้ำหนักมากกว่าแรงพยุง" if floats else "จมลง เพราะแรงพยุงมากกว่าน้ำหนัก"),
                        "ลอยนิ่งอยู่กับที่ เพราะแรงพยุงเท่ากับน้ำหนัก"),
                hint=BUOYANCY_HINT, topic=BUOYANCY_TOPIC,
            )
        floats = rng.random() < 0.5
        return _labelled(
            stem=f"วัตถุที่ปล่อยในน้ำจะ{'ลอย' if floats else 'จม'}ได้เมื่อใด",
            correct=("เมื่อแรงพยุงสูงสุดที่น้ำให้ได้มากกว่าหรือเท่ากับน้ำหนักของวัตถุ" if floats
                     else "เมื่อน้ำหนักของวัตถุมากกว่าแรงพยุงที่น้ำให้ได้"),
            wrongs=(("เมื่อน้ำหนักของวัตถุมากกว่าแรงพยุงที่น้ำให้ได้" if floats
                     else "เมื่อแรงพยุงสูงสุดที่น้ำให้ได้มากกว่าหรือเท่ากับน้ำหนักของวัตถุ"),
                    "เมื่อวัตถุมีขนาดใหญ่เสมอ ไม่ว่าจะหนักเท่าใด",
                    "เมื่อวัตถุมีสีอ่อน"),
            hint="เทียบน้ำหนักของวัตถุ (แรงลง) กับแรงพยุงของของเหลว (แรงขึ้น)",
            topic=BUOYANCY_TOPIC,
        )


@question_type(
    "phys.buoyancy_fluency",
    display_name={"th": "วิเคราะห์แรงพยุงจากค่าที่อ่านได้จากเครื่องชั่งสปริง"},
    level=SECONDARY_TWO, subject=SUBJECT, topic=BUOYANCY_TOPIC,
)
class BuoyancyFluency(QuestionType):
    """Readings in air and fully under water; the buoyant force and what it means."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        air = rng.randint(6, 20)
        buoyant = rng.randint(1, air - 2)
        water = air - buoyant
        return _labelled(
            stem=(f"แขวนก้อนวัตถุกับเครื่องชั่งสปริง อ่านได้ {air} นิวตันในอากาศ เมื่อหย่อนลงในน้ำจนจมมิด "
                  f"อ่านได้ {water} นิวตัน จากหลักฐานนี้ ข้อใดวิเคราะห์ได้ถูกต้อง"),
            correct=f"น้ำให้แรงพยุง {buoyant} นิวตันในทิศขึ้น น้อยกว่าน้ำหนัก {air} นิวตัน วัตถุจึงจม",
            wrongs=(f"น้ำให้แรงพยุง {water} นิวตันในทิศขึ้น วัตถุจึงลอยเมื่อปล่อยในน้ำ",
                    f"น้ำให้แรงพยุง {buoyant} นิวตันในทิศลง ทำให้วัตถุหนักขึ้นเมื่ออยู่ในน้ำ",
                    f"น้ำให้แรงพยุง {air + water} นิวตัน ซึ่งมากกว่าน้ำหนัก วัตถุจึงลอย"),
            hint="แรงพยุง = ค่าในอากาศ − ค่าในน้ำ แล้วเทียบกับน้ำหนักของวัตถุ",
            topic=BUOYANCY_TOPIC,
        )


@question_type(
    "phys.buoyancy_application",
    display_name={"th": "ใช้แรงพยุงอธิบายการจมการลอยในชีวิตประจำวัน"},
    level=SECONDARY_TWO, subject=SUBJECT, topic=BUOYANCY_TOPIC,
)
class BuoyancyApplication(QuestionType):
    """Authored cases, and an object's density against a liquid's."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        if rng.random() < 0.65:
            thing, rho = rng.choice(SOLIDS)
            liquid, rho_l = rng.choice([ell for ell in FLUIDS if ell[1] != rho])
            floats = rho < rho_l
            return _labelled(
                stem=(f"{thing}มีความหนาแน่น {rho:.2f} กรัมต่อลูกบาศก์เซนติเมตร ใส่ลงใน{liquid}ซึ่งมีความหนาแน่น "
                      f"{rho_l:.2f} กรัมต่อลูกบาศก์เซนติเมตร {thing}จะจมหรือลอย"),
                correct=("ลอย เพราะความหนาแน่นน้อยกว่าของเหลว แรงพยุงจึงมากพอกับน้ำหนักก่อนจมมิด" if floats
                         else "จม เพราะความหนาแน่นมากกว่าของเหลว แม้จมมิดแรงพยุงก็ยังน้อยกว่าน้ำหนัก"),
                wrongs=(("จม เพราะความหนาแน่นมากกว่าของเหลว แม้จมมิดแรงพยุงก็ยังน้อยกว่าน้ำหนัก" if floats
                         else "ลอย เพราะความหนาแน่นน้อยกว่าของเหลว แรงพยุงจึงมากพอกับน้ำหนักก่อนจมมิด"),
                        ("จม เพราะความหนาแน่นน้อยกว่าของเหลว" if floats else "ลอย เพราะความหนาแน่นมากกว่าของเหลว"),
                        "บอกไม่ได้ ต้องรู้ขนาดของวัตถุก่อน"),
                hint="วัตถุที่มีความหนาแน่นน้อยกว่าของเหลวจะลอย ที่มีความหนาแน่นมากกว่าจะจม",
                topic=BUOYANCY_TOPIC,
            )
        return _retopic(scenario_question(
            rng, BUOYANCY_SCENARIOS,
            hint="แรงพยุงขึ้นกับปริมาตรที่แทนที่ของเหลวและความหนาแน่นของของเหลว",
        ), BUOYANCY_TOPIC)
