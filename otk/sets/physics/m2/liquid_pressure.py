@question_type(
    "phys.liquid_pressure_foundation",
    display_name={"th": "บอกทิศทางของความดันของของเหลว"},
    level=SECONDARY_TWO, subject=SUBJECT, topic=LIQUID_TOPIC,
)
class LiquidPressureFoundation(QuestionType):
    """How liquid pressure acts, and which of two points has the greater pressure."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        roll = rng.random()
        if roll < 0.3:
            return _facts(rng, PRESSURE_FACTS, hint=PRESSURE_HINT, topic=LIQUID_TOPIC)
        if roll < 0.75:
            case = rng.choice(("depth", "liquid", "shape"))
            if case == "depth":
                d1, d2 = rng.sample(range(5, 61, 5), 2)
                liquid = rng.choice(("น้ำ", "น้ำเกลือ", "น้ำมันพืช"))
                stem = f"ในถัง{liquid}ใบเดียวกัน จุด ก ลึก {d1} เซนติเมตร จุด ข ลึก {d2} เซนติเมตร จุดใดมีความดันของของเหลวมากกว่า"
                answer = f"จุด {'ก' if d1 > d2 else 'ข'} เพราะอยู่ลึกกว่า"
                wrongs = (f"จุด {'ข' if d1 > d2 else 'ก'} เพราะอยู่ตื้นกว่า", "เท่ากัน เพราะอยู่ในถังเดียวกัน",
                          f"จุด {'ข' if d1 > d2 else 'ก'} เพราะอยู่ลึกกว่า")
            elif case == "liquid":
                depth = rng.randrange(10, 51, 5)
                dense, light = rng.choice((("น้ำเกลือ", "น้ำ"), ("น้ำ", "น้ำมันพืช"), ("น้ำเกลือ", "น้ำมันพืช")))
                first, second = rng.sample((dense, light), 2)
                stem = f"ที่ความลึก {depth} เซนติเมตรเท่ากัน ใน{first}กับใน{second} ที่ใดมีความดันของของเหลวมากกว่า"
                answer = f"ใน{dense} เพราะมีความหนาแน่นมากกว่า"
                wrongs = (f"ใน{light} เพราะมีความหนาแน่นน้อยกว่า", "เท่ากัน เพราะลึกเท่ากัน", f"ใน{light} เพราะมีความหนาแน่นมากกว่า")
            else:
                depth = rng.randrange(10, 51, 5)
                wide, narrow = rng.choice((("ถังกว้าง", "แก้วแคบ"), ("สระน้ำ", "ท่อแคบ"), ("อ่างใหญ่", "ขวดเล็ก")))
                stem = f"ที่ความลึก {depth} เซนติเมตรเท่ากัน ในน้ำที่อยู่ใน{wide}กับใน{narrow} ที่ใดมีความดันของน้ำมากกว่า"
                answer = "เท่ากัน เพราะความดันขึ้นกับความลึกและชนิดของเหลว ไม่ใช่รูปร่างภาชนะ"
                wrongs = (f"ใน{wide} เพราะมีปริมาณน้ำมากกว่าหลายเท่า", f"ใน{narrow} เพราะน้ำถูกบีบให้อยู่ในที่แคบ ความดันจึงรวมกันมากขึ้น",
                          f"ใน{wide} เพราะก้นภาชนะกว้างกว่า น้ำจึงกดทับได้มากกว่า")
            return _labelled(stem=stem, correct=answer, wrongs=wrongs, hint=PRESSURE_HINT, topic=LIQUID_TOPIC)
        return _labelled(
            stem=rng.choice(("ข้อใดกล่าวถึงความดันของของเหลวได้ถูกต้อง",
                             "เจาะรูด้านข้างขวดน้ำหลายระดับ น้ำพุ่งออกจากรูใดแรงที่สุด และเพราะเหตุใด")),
            correct="ของเหลวดันทุกทิศทาง และยิ่งลึกความดันยิ่งมาก รูล่างสุดจึงมีน้ำพุ่งแรงที่สุด",
            wrongs=("ของเหลวออกแรงกดลงเท่านั้น รูบนสุดจึงมีน้ำพุ่งแรงที่สุดเพราะอยู่ใกล้ผิวน้ำ",
                    "ความดันเท่ากันทุกความลึก น้ำจึงพุ่งแรงเท่ากันทุกรูไม่ว่าอยู่สูงหรือต่ำ",
                    "ยิ่งตื้นความดันยิ่งมาก รูบนสุดจึงมีน้ำพุ่งแรงที่สุด"),
            hint="น้ำหนักของของเหลวที่อยู่ด้านบนทำให้ความดันที่ลึกกว่ามีมากกว่า",
            topic=LIQUID_TOPIC,
        )


@question_type(
    "phys.liquid_pressure_fluency",
    display_name={"th": "อธิบายปัจจัยที่มีผลต่อความดันของของเหลวจากผลการทดลอง"},
    level=SECONDARY_TWO, subject=SUBJECT, topic=LIQUID_TOPIC,
)
class LiquidPressureFluency(QuestionType):
    """Three one-factor results; explain depth, liquid and container together."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        shallow, deep = sorted(rng.sample((5, 10, 15, 20, 25), 2))
        dense, light = rng.choice(LIQUIDS)
        near, far = rng.randint(3, 6), rng.randint(9, 14)
        side = rng.randint(4, 10)
        record = (f"การทดลองที่ 1 (น้ำ ภาชนะเดียวกัน): ที่ลึก {shallow} เซนติเมตร น้ำพุ่งออกจากรูได้ไกล {near} เซนติเมตร "
                  f"ที่ลึก {deep} เซนติเมตร พุ่งได้ไกล {far} เซนติเมตร / "
                  f"การทดลองที่ 2 (ความลึกเท่ากัน): {dense}พุ่งได้ไกลกว่า{light} / "
                  f"การทดลองที่ 3 (น้ำ ความลึกเท่ากัน): ภาชนะแคบและภาชนะกว้างพุ่งได้ไกล {side} เซนติเมตรเท่ากัน")
        return parts_item(
            rng, liquid_parts(shallow, deep, dense, light),
            stem=(f"นักเรียนออกแบบการทดลองเจาะรูภาชนะที่เปลี่ยนเพียงปัจจัยเดียวในแต่ละการทดลอง ได้ผลดังนี้ — {record} "
                  "จากผลการทดลอง ข้อใดอธิบายปัจจัยที่มีผลต่อความดันของของเหลวได้ถูกต้องทั้งหมด"),
            hint="น้ำพุ่งไกลกว่าแสดงว่าความดันมากกว่า อ่านทีละการทดลอง ข้อที่ผิดจะผิดอย่างน้อยหนึ่งปัจจัย",
            topic=LIQUID_TOPIC,
        )


@question_type(
    "phys.liquid_pressure_application",
    display_name={"th": "ใช้ความดันของของเหลวอธิบายการออกแบบและปรากฏการณ์"},
    level=SECONDARY_TWO, subject=SUBJECT, topic=LIQUID_TOPIC,
)
class LiquidPressureApplication(QuestionType):
    """Authored cases, taps below a water tower, and a diver's two depths."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        roll = rng.random()
        if roll < 0.35:
            depths = rng.sample(range(2, 21), 3)
            rows = [f"ก๊อก{n} อยู่ต่ำกว่าผิวน้ำในถัง {d} เมตร" for n, d in zip(("ที่ 1", "ที่ 2", "ที่ 3"), depths)]
            strong = rng.random() < 0.6
            pick = (max if strong else min)(range(3), key=lambda i: depths[i])
            names = ("ก๊อกที่ 1", "ก๊อกที่ 2", "ก๊อกที่ 3")
            return _labelled(
                stem=(f"บ้านรับน้ำจากถังเก็บน้ำบนหอสูง โดย{' / '.join(rows)} "
                      f"เมื่อเปิดก๊อกทั้งสามพร้อมกัน ก๊อกใดน้ำไหลแรง{'ที่สุด' if strong else 'น้อยที่สุด'}"),
                correct=names[pick],
                wrongs=(*(n for i, n in enumerate(names) if i != pick), "ทุกก๊อกไหลแรงเท่ากัน"),
                hint="ก๊อกที่อยู่ต่ำกว่าผิวน้ำมาก ความดันของน้ำที่ก๊อกยิ่งมาก น้ำจึงไหลแรง",
                topic=LIQUID_TOPIC,
            )
        if roll < 0.65:
            d1, d2 = sorted(rng.sample(range(2, 31), 2))
            place = rng.choice(("ทะเล", "สระว่ายน้ำลึก", "ทะเลสาบ", "เหมืองหินที่มีน้ำขัง"))
            return _labelled(
                stem=f"นักดำน้ำดำลงใน{place} ครั้งแรกลึก {d1} เมตร ครั้งที่สองลึก {d2} เมตร ข้อใดถูกต้อง",
                correct=f"ที่ลึก {d2} เมตร ความดันของน้ำมากกว่า จึงรู้สึกหูอื้อมากกว่า",
                wrongs=(f"ที่ลึก {d1} เมตร ความดันของน้ำมากกว่า จึงรู้สึกหูอื้อมากกว่า",
                        "ความดันของน้ำเท่ากันทุกความลึก",
                        f"ที่ลึก {d2} เมตร ความดันของน้ำน้อยกว่า เพราะอยู่ไกลจากผิวน้ำ"),
                hint="ยิ่งลึก น้ำที่อยู่ด้านบนยิ่งมาก ความดันของน้ำยิ่งมาก",
                topic=LIQUID_TOPIC,
            )
        return _retopic(scenario_question(
            rng, LIQUID_SCENARIOS,
            hint="ความดันของของเหลวขึ้นกับความลึกและความหนาแน่น ไม่ขึ้นกับรูปร่างภาชนะ",
        ), LIQUID_TOPIC)
