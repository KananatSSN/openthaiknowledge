@question_type(
    "phys.field_compare_foundation",
    display_name={"th": "ระบุแหล่งของสนามแต่ละชนิด"},
    level=SECONDARY_TWO, subject=SUBJECT, topic=FIELDS_TOPIC,
)
class FieldCompareFoundation(QuestionType):
    """One field; what makes it, which field an event shows, or a field fact."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        roll = rng.random()
        if roll < 0.35:
            stem, right, wrongs = rng.choice(FIELD_FACTS)
            return _labelled(stem=stem, correct=right, wrongs=tuple(wrongs),
                             hint="แรงแม่เหล็กและแรงไฟฟ้ามีทั้งดึงดูดและผลัก แรงโน้มถ่วงมีแต่ดึงดูด และทั้งสามกระทำได้โดยไม่สัมผัส",
                             topic=FIELDS_TOPIC)
        if roll < 0.75:
            event, field = rng.choice(FIELD_EVENTS)
            return _labelled(
                stem=f"\"{event}\" เกิดจากแรงในสนามใด",
                correct=field,
                wrongs=(*(f for f in ("สนามแม่เหล็ก", "สนามไฟฟ้า", "สนามโน้มถ่วง") if f != field), "ไม่เกี่ยวกับสนามใด"),
                hint="สนามแม่เหล็กมาจากแม่เหล็ก สนามไฟฟ้ามาจากประจุ สนามโน้มถ่วงมาจากมวล",
                topic=FIELDS_TOPIC,
            )
        answers = {"สนามแม่เหล็ก": "แม่เหล็ก", "สนามไฟฟ้า": "วัตถุที่มีประจุไฟฟ้า", "สนามโน้มถ่วง": "วัตถุที่มีมวล"}
        field = rng.choice(tuple(answers))
        return _labelled(
            stem=f"แหล่งของ{field}คือสิ่งใด",
            correct=answers[field],
            wrongs=(*(v for k, v in answers.items() if k != field), "แสงอาทิตย์"),
            hint="สนามแม่เหล็กมาจากแม่เหล็ก สนามไฟฟ้ามาจากประจุ สนามโน้มถ่วงมาจากมวล",
            topic=FIELDS_TOPIC,
        )


@question_type(
    "phys.field_compare_fluency",
    display_name={"th": "เปรียบเทียบแหล่งและทิศของแรงในสนามทั้งสามจากข้อมูลที่รวบรวมได้"},
    level=SECONDARY_TWO, subject=SUBJECT, topic=FIELDS_TOPIC,
)
class FieldCompareFluency(QuestionType):
    """Collected observations of all three fields; source and force direction for each."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        seen = [rng.choice((first, *more)) for first, more in zip(OBSERVATIONS, MORE_OBSERVATIONS)]
        rng.shuffle(seen)
        return parts_item(
            rng, FIELD_PARTS,
            stem=(f"ข้อมูลที่รวบรวมได้ — {' / '.join(seen)} "
                  "จากข้อมูลนี้ ข้อใดเปรียบเทียบแหล่งของสนามและทิศของแรงในสนามทั้งสามได้ถูกต้องทั้งหมด"),
            hint="ตรวจทีละสนาม: สิ่งใดทำให้เกิดสนาม และแรงดึงหรือผลักอะไร ข้อที่ผิดจะผิดอย่างน้อยหนึ่งสนาม",
            topic=FIELDS_TOPIC,
        )


@question_type(
    "phys.field_compare_application",
    display_name={"th": "ใช้ความรู้เรื่องสนามอธิบายปรากฏการณ์"},
    level=SECONDARY_TWO, subject=SUBJECT, topic=FIELDS_TOPIC,
)
class FieldCompareApplication(QuestionType):
    """Authored cases, and whether a named pair attracts or repels."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        if rng.random() < 0.65:
            kind = rng.choice(("magnet", "charge", "gravity"))
            if kind == "magnet":
                a, b = rng.choice(("เหนือ", "ใต้")), rng.choice(("เหนือ", "ใต้"))
                pair = f"ขั้ว{a}ของแม่เหล็กแท่งหนึ่งกับขั้ว{b}ของแม่เหล็กอีกแท่ง"
                attract = a != b
                reason = "ขั้วต่างกันดึงดูดกัน" if attract else "ขั้วเหมือนกันผลักกัน"
                field = "สนามแม่เหล็ก"
            elif kind == "charge":
                x, y = rng.sample(("ลูกโป่ง", "แท่งพลาสติก", "แท่งแก้ว", "ลูกพิท", "หวี"), 2)
                a, b = rng.choice(("บวก", "ลบ")), rng.choice(("บวก", "ลบ"))
                pair = f"{x}ที่มีประจุ{a}กับ{y}ที่มีประจุ{b}"
                attract = a != b
                reason = "ประจุต่างชนิดดึงดูดกัน" if attract else "ประจุชนิดเดียวกันผลักกัน"
                field = "สนามไฟฟ้า"
            else:
                pair = rng.choice(("โลกกับดวงจันทร์", "ดวงอาทิตย์กับโลก", "โลกกับลูกมะพร้าวบนต้น", "โลกกับนักบินอวกาศในสถานีอวกาศ",
                                   "ดวงอาทิตย์กับดาวพฤหัสบดี", "โลกกับดาวเทียม"))
                attract, reason, field = True, "แรงโน้มถ่วงมีแต่แรงดึงดูด", "สนามโน้มถ่วง"
            correct = f"{'ดึงดูดกัน' if attract else 'ผลักกัน'} เพราะ{reason}"
            others = [f"{'ผลักกัน' if attract else 'ดึงดูดกัน'} เพราะ{reason}", "ไม่มีแรงกระทำต่อกัน เพราะไม่ได้สัมผัสกัน",
                      f"{'ผลักกัน' if attract else 'ดึงดูดกัน'} เพราะแรงใน{field}มีแต่แรง{'ผลัก' if attract else 'ดึงดูด'}"]
            return _labelled(
                stem=f"{pair} ออกแรงกระทำต่อกันอย่างไร",
                correct=correct, wrongs=tuple(others),
                hint="แรงแม่เหล็กและแรงไฟฟ้ามีทั้งดึงดูดและผลัก ส่วนแรงโน้มถ่วงมีแต่ดึงดูด",
                topic=FIELDS_TOPIC,
            )
        return _retopic(scenario_question(
            rng, FIELDS_SCENARIOS,
            hint="แรงแม่เหล็กและแรงไฟฟ้ามีทั้งดึงดูดและผลัก ส่วนแรงโน้มถ่วงมีแต่ดึงดูด",
        ), FIELDS_TOPIC)
