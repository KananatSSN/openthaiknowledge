@question_type(
    "phys.thermal_expansion_benefit_foundation",
    display_name={"th": "บอกประโยชน์ของความรู้เรื่องการขยายตัวและหดตัวของสสาร"},
    level=FIRST_SECONDARY, subject=SUBJECT, topic=THERMAL_EXPANSION_BENEFIT_TOPIC,
)
class ThermalExpansionBenefitFoundation(QuestionType):
    """What knowing about expansion is good for."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        stem, right, wrongs = rng.choice(BENEFIT_EXPAND_FACTS)
        return _labelled(stem=stem, correct=right, wrongs=tuple(wrongs),
                         hint="วัสดุที่ขยายหรือหดตัวโดยไม่มีที่รองรับอาจแตกหักหรือทำให้ชิ้นส่วนติดขัดกัน", topic=THERMAL_EXPANSION_BENEFIT_TOPIC)


@question_type(
    "phys.thermal_expansion_benefit_fluency",
    display_name={"th": "วิเคราะห์สถานการณ์ปัญหาและเสนอแนะวิธีแก้ปัญหาการขยายตัวของสสาร"},
    level=FIRST_SECONDARY, subject=SUBJECT, topic=THERMAL_EXPANSION_BENEFIT_TOPIC,
)
class ThermalExpansionBenefitFluency(QuestionType):
    """A real problem caused by expansion or contraction; the method that fixes it."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        index = rng.randrange(len(EXPANSION_PROBLEMS))
        problem = EXPANSION_PROBLEMS[index]
        others = [p.method for i, p in enumerate(EXPANSION_PROBLEMS) if i != index]
        return _labelled(
            stem=f"{problem.case} ควรแก้ปัญหานี้ด้วยวิธีใด",
            correct=problem.method,
            wrongs=tuple(others),
            hint="พิจารณาว่าปัญหาเกิดจากการขยายตัวหรือหดตัว แล้วเลือกวิธีที่รองรับการเปลี่ยนแปลงนั้น",
            topic=THERMAL_EXPANSION_BENEFIT_TOPIC,
        )


@question_type(
    "phys.thermal_expansion_benefit_application",
    display_name={"th": "ประเมินการออกแบบโครงสร้างให้รองรับการขยายตัวและหดตัว"},
    level=FIRST_SECONDARY, subject=SUBJECT, topic=THERMAL_EXPANSION_BENEFIT_TOPIC,
)
class ThermalExpansionBenefitApplication(QuestionType):
    """Authored designs, and whether a design leans on expansion or contraction."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        if rng.random() < 0.3:
            return _retopic(scenario_question(
                rng, EXPANSION_BENEFIT_SCENARIOS,
                hint="โครงสร้างขนาดใหญ่ต้องมีที่ว่างหรือกลไกรองรับการขยายและหดตัวตามอุณหภูมิเสมอ",
            ), THERMAL_EXPANSION_BENEFIT_TOPIC)
        design, kind = rng.choice(DESIGNS)
        place = rng.choice(("ในเมือง", "ในโรงงาน", "ในชนบท", "ริมทะเล", "บนภูเขา", "ในทะเลทราย"))
        right = ("รองรับการขยายตัวเมื่ออุณหภูมิสูงขึ้น" if kind == "ขยายตัว" else "อาศัยหรือรองรับการหดตัวเมื่ออุณหภูมิลดลง")
        other = ("อาศัยหรือรองรับการหดตัวเมื่ออุณหภูมิลดลง" if kind == "ขยายตัว" else "รองรับการขยายตัวเมื่ออุณหภูมิสูงขึ้น")
        return _labelled(stem=f"ช่างงานหนึ่ง{place}{design} การออกแบบนี้เกี่ยวข้องกับความรู้ข้อใดเป็นหลัก", correct=right,
                         wrongs=(other, "ทำให้วัสดุมีมวลเพิ่มขึ้น", "ทำให้วัสดุนำไฟฟ้าได้ดีขึ้น"),
                         hint="พิจารณาว่าการออกแบบเผื่อที่ให้วัสดุยาวขึ้น หรือใช้ประโยชน์จากการที่วัสดุหดสั้นลง", topic=THERMAL_EXPANSION_BENEFIT_TOPIC)
