@question_type(
    "phys.air_pressure_height_foundation",
    display_name={"th": "บอกความสัมพันธ์ระหว่างความดันอากาศกับความสูง"},
    level=SECONDARY_ONE, subject=SUBJECT, topic=PRESSURE_TOPIC,
)
class AirPressureHeightFoundation(QuestionType):
    """How air pressure relates to height, in general or between two named places."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        roll = rng.random()
        if roll < 0.3:
            stem, right, wrongs = rng.choice(PRESSURE_FACTS)
            return _labelled(stem=stem, correct=right, wrongs=tuple(wrongs), hint=PRESSURE_HINT, topic=PRESSURE_TOPIC)
        if roll < 0.8:
            (a, ha), (b, hb) = rng.sample(PLACES, 2)
            higher_p = rng.random() < 0.5
            low, high = (a, b) if ha < hb else (b, a)
            pick = low if higher_p else high
            other = high if higher_p else low
            return _labelled(
                stem=f"{a} (สูง {ha:,} เมตร) กับ{b} (สูง {hb:,} เมตร) ที่ใดมีความดันอากาศ{'สูง' if higher_p else 'ต่ำ'}กว่า",
                correct=f"{pick} เพราะ{'อยู่ต่ำกว่า มีอากาศกดทับด้านบนมากกว่า' if higher_p else 'อยู่สูงกว่า มีอากาศกดทับด้านบนน้อยกว่า'}",
                wrongs=(f"{other} เพราะ{'อยู่สูงกว่า ใกล้ท้องฟ้ามากกว่า' if higher_p else 'อยู่ต่ำกว่า มีอากาศกดทับด้านบนน้อยกว่า'}",
                        "เท่ากัน เพราะความดันอากาศไม่ขึ้นกับความสูง",
                        f"{other} เพราะ{'อยู่ต่ำกว่า มีอากาศกดทับด้านบนมากกว่า' if higher_p else 'อยู่สูงกว่า มีอากาศกดทับด้านบนน้อยกว่า'}"),
                hint=PRESSURE_HINT, topic=PRESSURE_TOPIC,
            )
        return _labelled(
            stem="เมื่อสูงขึ้นจากพื้นโลก ความดันอากาศเปลี่ยนแปลงอย่างไร",
            correct="ความดันอากาศลดลง เพราะอากาศที่อยู่เหนือขึ้นไปมีน้อยลง",
            wrongs=("ความดันอากาศเพิ่มขึ้น เพราะอยู่ใกล้ดวงอาทิตย์มากขึ้น",
                    "ความดันอากาศเท่าเดิมทุกความสูง",
                    "ความดันอากาศลดลง เพราะอากาศที่อยู่เหนือขึ้นไปมีมากขึ้น"),
            hint="ความดันอากาศเกิดจากน้ำหนักของอากาศที่กดทับอยู่ด้านบน",
            topic=PRESSURE_TOPIC,
        )


@question_type(
    "phys.air_pressure_height_fluency",
    display_name={"th": "อธิบายความสัมพันธ์ระหว่างความดันอากาศกับความสูงจากแบบจำลองและข้อมูล"},
    level=SECONDARY_ONE, subject=SUBJECT, topic=PRESSURE_TOPIC,
)
class AirPressureHeightFluency(QuestionType):
    """A stacked-sponge model and pressure readings at three heights; explain the relation."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        chosen = sorted(rng.sample(PLACES, 3), key=lambda p: p[1])
        shuffled = list(chosen)
        rng.shuffle(shuffled)
        record = " / ".join(f"{name} สูง {h:,} เมตร: {pressure_at(h)} กิโลพาสคัล" for name, h in shuffled)
        low, high = chosen[0][0], chosen[-1][0]
        return _labelled(
            stem=(f"แบบจำลอง: วางฟองน้ำซ้อนกัน 5 ชั้น ฟองน้ำชั้นล่างสุดถูกกดยุบมากที่สุด ชั้นบนสุดแทบไม่ยุบ "
                  f"ข้อมูลที่วัดได้: {record} "
                  "จากแบบจำลองและข้อมูล ข้อใดอธิบายความสัมพันธ์ได้ถูกต้อง"),
            correct=(f"ยิ่งสูงความดันอากาศยิ่งลดลง {high}จึงมีความดันต่ำที่สุด เพราะมีอากาศกดทับด้านบนน้อยที่สุด "
                     "เหมือนฟองน้ำชั้นบน"),
            wrongs=(f"ยิ่งสูงความดันอากาศยิ่งเพิ่มขึ้น {high}จึงมีความดันสูงที่สุด เพราะเหมือนฟองน้ำชั้นบนที่ถูกกดมากที่สุด",
                    f"ยิ่งสูงความดันอากาศยิ่งลดลง {low}จึงมีความดันต่ำที่สุด เพราะอยู่ไกลจากอากาศชั้นบนที่กดทับลงมา",
                    "ความดันอากาศไม่ขึ้นกับความสูง ความต่างที่วัดได้เกิดจากเครื่องมือวัดคลาดเคลื่อนในแต่ละที่"),
            hint="ฟองน้ำชั้นล่างเหมือนอากาศใกล้พื้นที่ถูกอากาศทั้งหมดกดทับ เรียงข้อมูลตามความสูงแล้วดูแนวโน้ม",
            topic=PRESSURE_TOPIC,
        )


@question_type(
    "phys.air_pressure_height_application",
    display_name={"th": "ใช้ความสัมพันธ์ของความดันอากาศกับความสูงอธิบายสถานการณ์"},
    level=SECONDARY_ONE, subject=SUBJECT, topic=PRESSURE_TOPIC,
)
class AirPressureHeightApplication(QuestionType):
    """Authored cases, and which of two barometer readings was taken higher up."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        if rng.random() < 0.6:
            p1, p2 = rng.sample(range(62, 102), 2)
            who = rng.choice(("นักปีนเขา", "นักสำรวจ", "นักเรียนที่ไปทัศนศึกษา", "นักปั่นจักรยานทางไกล"))
            return _labelled(
                stem=(f"{who}วัดความดันอากาศด้วยบารอมิเตอร์ ที่จุด ก ได้ {p1} กิโลพาสคัล ที่จุด ข ได้ {p2} กิโลพาสคัล "
                      "จุดใดอยู่สูงกว่า และเพราะเหตุใด"),
                correct=f"จุด {'ก' if p1 < p2 else 'ข'} เพราะความดันอากาศต่ำกว่า แสดงว่ามีอากาศกดทับด้านบนน้อยกว่า",
                wrongs=(f"จุด {'ข' if p1 < p2 else 'ก'} เพราะความดันอากาศสูงกว่า แสดงว่าอยู่สูงกว่า",
                        f"จุด {'ข' if p1 < p2 else 'ก'} เพราะความดันอากาศต่ำกว่า แสดงว่ามีอากาศกดทับด้านบนน้อยกว่า",
                        "สูงเท่ากัน เพราะความดันอากาศไม่เกี่ยวกับความสูง"),
                hint="ยิ่งสูง ความดันอากาศยิ่งต่ำ จุดที่ความดันต่ำกว่าจึงอยู่สูงกว่า",
                topic=PRESSURE_TOPIC,
            )
        return _retopic(scenario_question(
            rng, PRESSURE_SCENARIOS,
            hint="ที่สูงความดันอากาศต่ำ ที่ต่ำความดันอากาศสูง ภาชนะปิดจะบุบหรือพองตามความต่างของความดัน",
        ), PRESSURE_TOPIC)
