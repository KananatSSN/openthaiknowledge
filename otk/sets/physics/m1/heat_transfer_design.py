        changes = rng.sample(range(3, 31), 4)
        after = [start + c if keep_cold else start - c for c in changes]
        best = BOXES[changes.index(min(changes))]
        table = " / ".join(f"{b} ({m}) {a} °C" for b, m, a in zip(BOXES, mats, after))
        what = f"น้ำเย็น {start} °C" if keep_cold else f"น้ำร้อน {start} °C"
        return _labelled(stem=f"นักเรียนทดสอบกล่องสี่แบบโดยใส่{what} ไว้ 1 ชั่วโมง อุณหภูมิหลังทดสอบคือ {table} กล่องใดเป็นฉนวนความร้อนที่ดีที่สุด",
                         correct=best, wrongs=tuple(b for b in BOXES if b != best),
                         hint="ฉนวนที่ดีที่สุดทำให้อุณหภูมิของน้ำเปลี่ยนไปจากเดิมน้อยที่สุด", topic=HEAT_TRANSFER_DESIGN_TOPIC)
