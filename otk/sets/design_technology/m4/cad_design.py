@question_type(
    "tech.cad_design_fluency",
    display_name={"th": "คำนวณขนาดจากแบบที่เขียนตามมาตราส่วน"},
    level=M4, subject=SUBJECT, topic=CAD_TOPIC,
)
class CadDesignFluency(QuestionType):
    def build(self, rng: Random, **params):
        scale = rng.choice((2, 5, 10, 20, 25, 50, 100))
        hint = f"มาตราส่วน 1 : {scale} หมายความว่า 1 หน่วยในแบบเท่ากับ {scale} หน่วยของจริง"
        if rng.random() < 0.5:
            drawn = rng.randint(2, 30)
            real = drawn * scale
            return _labelled(
                stem=f"แบบชิ้นงานเขียนด้วยมาตราส่วน 1 : {scale} ถ้าความยาวในแบบเป็น {drawn} เซนติเมตร ความยาวจริงเป็นกี่เซนติเมตร",
                correct=f"{real} เซนติเมตร",
                wrongs=tuple(f"{w} เซนติเมตร" for w in rng.sample(
                    _near(real, (drawn + scale, real * 10, real // 10 if real >= 10 else real + 5, drawn)), 3)),
                hint=hint, topic=CAD_TOPIC,
            )
        drawn = rng.randint(2, 30)
        real = drawn * scale
        return _labelled(
            stem=f"ชิ้นงานยาวจริง {real} เซนติเมตร ถ้าเขียนแบบด้วยมาตราส่วน 1 : {scale} ความยาวในแบบเป็นกี่เซนติเมตร",
            correct=f"{drawn} เซนติเมตร",
            wrongs=tuple(f"{w} เซนติเมตร" for w in rng.sample(
                _near(drawn, (real * scale, real - scale, drawn * 10, real)), 3)),
            hint=hint, topic=CAD_TOPIC,
        )


