@question_type(
    "tech.complex_problem_fluency",
    display_name={"th": "วิเคราะห์ลำดับสาเหตุเพื่อหาต้นเหตุของปัญหา"},
    level=M4, subject=SUBJECT, topic=COMPLEX_TOPIC,
)
class ComplexProblemFluency(QuestionType):
    def build(self, rng: Random, **params):
        chain = rng.choice(CHAINS)
        told = " ".join(f"“{chain[i]}” เพราะ “{chain[i + 1]}”" for i in range(len(chain) - 1))
        hint = "ไล่ถามว่าเกิดจากอะไรไปทีละขั้น สาเหตุสุดท้ายที่แก้แล้วปัญหาทั้งแถวหายไปคือต้นเหตุ"
        kind = rng.randrange(3)
        if kind == 0:
            return _labelled(stem=f"จากการวิเคราะห์ {told} ต้นเหตุของปัญหาคือข้อใด",
                             correct=chain[-1], wrongs=tuple(chain[:-1]),
                             hint=hint, topic=COMPLEX_TOPIC)
        i = rng.randrange(1, len(chain) - 1)
        if kind == 1:
            others = [c for j, c in enumerate(chain) if j not in (i, i + 1)]
            return _labelled(stem=f"จากการวิเคราะห์ {told} “{chain[i]}” เกิดจากสาเหตุโดยตรงใด",
                             correct=chain[i + 1], wrongs=tuple(others),
                             hint=hint, topic=COMPLEX_TOPIC)
        others = [c for j, c in enumerate(chain) if j not in (i, i - 1)]
        return _labelled(stem=f"จากการวิเคราะห์ {told} ผลโดยตรงของ “{chain[i]}” คือข้อใด",
                         correct=chain[i - 1], wrongs=tuple(others),
                         hint=hint, topic=COMPLEX_TOPIC)


