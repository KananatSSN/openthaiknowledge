@question_type(
    "tech.technology_impact_foundation",
    display_name={"th": "จำแนกผลกระทบของเทคโนโลยีต่อมนุษย์ สังคม เศรษฐกิจ และสิ่งแวดล้อม"},
    level={"th": "ม.4"}, subject=SUBJECT, topic=IMPACT_TOPIC,
)
class TechnologyImpactFoundation(QuestionType):
    """Name the side an effect falls on, or pick the effect on a named side."""

    def build(self, rng: Random, **params):
        technology = rng.choice(list(IMPACTS))
        effects = IMPACTS[technology]
        dimension = rng.choice(list(effects))
        hint = ("มนุษย์คือสุขภาพและความเป็นอยู่ของแต่ละคน สังคมคือความสัมพันธ์และการอยู่ร่วมกัน "
                "เศรษฐกิจคือรายได้ ค่าใช้จ่าย และธุรกิจ สิ่งแวดล้อมคือมลพิษ ขยะ และทรัพยากร")
        if rng.random() < 0.5:
            return _labelled(
                stem=f"“{effects[dimension]}” เป็นผลกระทบของ{technology}ต่อด้านใด",
                correct=dimension, wrongs=tuple(d for d in DIMENSIONS if d != dimension),
                hint=hint, topic=IMPACT_TOPIC,
            )
        wrongs = [text for d, text in effects.items() if d != dimension]
        while len(wrongs) < 3:
            other = rng.choice([t for t in IMPACTS if t != technology])
            candidates = [text for d, text in IMPACTS[other].items()
                          if d != dimension and text not in wrongs]
            wrongs.append(rng.choice(candidates))
        return _labelled(
            stem=f"ข้อใดเป็นผลกระทบของ{technology}ต่อด้าน{dimension}",
            correct=effects[dimension], wrongs=tuple(wrongs),
            hint=hint, topic=IMPACT_TOPIC,
        )


@question_type(
    "tech.technology_impact_fluency",
    display_name={"th": "เลือกแนวทางพัฒนาเทคโนโลยีเพื่อลดผลกระทบ"},
    level={"th": "ม.4"}, subject=SUBJECT, topic=IMPACT_TOPIC,
)
class TechnologyImpactFluency(QuestionType):
    """The development that answers a named harm, not another one."""

    def build(self, rng: Random, **params):
        index = rng.randrange(len(REMEDIES))
        technology, harm, remedy = REMEDIES[index]
        others = [r for i, (_, _, r) in enumerate(REMEDIES) if i != index]
        return _labelled(
            stem=(f"{technology}มีผลกระทบคือ{harm} "
                  f"แนวทางการพัฒนาเทคโนโลยีข้อใดลดผลกระทบนี้ได้ตรงที่สุด"),
            correct=remedy, wrongs=tuple(others),
            hint="เลือกแนวทางที่แก้ที่ต้นเหตุของผลกระทบข้อนั้น ไม่ใช่แนวทางที่ดีแต่แก้ปัญหาอื่น",
            topic=IMPACT_TOPIC,
        )


@question_type(
    "tech.technology_impact_application",
    display_name={"th": "ประเมินข้อเสนอการใช้เทคโนโลยีรอบด้าน"},
    level={"th": "ม.4"}, subject=SUBJECT, topic=IMPACT_TOPIC,
)
class TechnologyImpactApplication(QuestionType):
    """The assessment that weighs a proposal on every side."""

    def build(self, rng: Random, **params):
        bank = tuple(
            (
                f"{proposal} ข้อใดประเมินผลกระทบของข้อเสนอนี้ได้รอบด้านและสมเหตุสมผลที่สุด",
                correct,
                wrongs,
            )
            for proposal, correct, wrongs in PROPOSALS
        )
        return contextual_scenario_question(
            rng, bank,
            hint=("การประเมินที่ดีชั่งทั้งผลดีและผลเสีย ต่อมนุษย์ สังคม เศรษฐกิจ และสิ่งแวดล้อม "
                  "และเสนอวิธีลดผลเสีย ไม่ตัดสินจากด้านเดียว"),
            topic=IMPACT_TOPIC,
        )
