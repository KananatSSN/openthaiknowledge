@question_type(
    "tech.technology_link_foundation",
    display_name={"th": "ระบุความรู้ทางวิทยาศาสตร์และคณิตศาสตร์ที่เทคโนโลยีใช้"},
    level={"th": "ม.3"}, subject=SUBJECT, topic=LINK_TOPIC,
)
class TechnologyLinkFoundation(QuestionType):
    """The knowledge a technology rests on, in either direction."""

    def build(self, rng: Random, **params):
        index = rng.randrange(len(FOUNDATIONS))
        technology, knowledge = FOUNDATIONS[index]
        others = [row for i, row in enumerate(FOUNDATIONS) if i != index]
        picked = rng.sample(others, 3)
        hint = "ถามว่าเทคโนโลยีนั้นทำงานได้เพราะหลักการใด หรือต้องคำนวณอะไรจึงจะออกแบบได้"
        if rng.random() < 0.5:
            return _labelled(
                stem=f"{technology}ทำงานหรือออกแบบได้โดยอาศัยความรู้ใดเป็นหลัก",
                correct=knowledge, wrongs=tuple(k for _, k in picked),
                hint=hint, topic=LINK_TOPIC,
            )
        return _labelled(
            stem=f"ความรู้ที่ว่า “{knowledge}” ถูกนำไปใช้ในเทคโนโลยีใด",
            correct=technology, wrongs=tuple(t for t, _ in picked),
            hint=hint, topic=LINK_TOPIC,
        )


@question_type(
    "tech.technology_link_fluency",
    display_name={"th": "เลือกความรู้จากศาสตร์อื่นมาเป็นแนวทางแก้ปัญหา"},
    level={"th": "ม.3"}, subject=SUBJECT, topic=LINK_TOPIC,
)
class TechnologyLinkFluency(QuestionType):
    """Which science or mathematics a stated problem calls for."""

    def build(self, rng: Random, **params):
        index = rng.randrange(len(PROBLEMS))
        goal, knowledge = PROBLEMS[index]
        others = [k for i, (_, k) in enumerate(PROBLEMS) if i != index]
        return _labelled(
            stem=f"ถ้าต้องการ{goal} ควรนำความรู้ใดมาใช้เป็นแนวทางแก้ปัญหา",
            correct=knowledge, wrongs=tuple(others),
            hint="ระบุก่อนว่าปัญหาเกี่ยวกับความร้อน แรง ไฟฟ้า แสง เสียง สาร หรือการคำนวณขนาด",
            topic=LINK_TOPIC,
        )


@question_type(
    "tech.technology_link_application",
    display_name={"th": "วิเคราะห์การเปลี่ยนแปลงของเทคโนโลยีและความสัมพันธ์กับศาสตร์อื่น"},
    level={"th": "ม.3"}, subject=SUBJECT, topic=LINK_TOPIC,
)
class TechnologyLinkApplication(QuestionType):
    """Read a technology's history for its cause and the knowledge behind it."""

    def build(self, rng: Random, **params):
        bank = tuple(
            (
                f"{history.story} ข้อใดวิเคราะห์สาเหตุของการเปลี่ยนแปลงนี้ "
                f"และความสัมพันธ์กับศาสตร์อื่นได้ถูกต้อง",
                history.analysis,
                (*history.wrongs, *ANY_HISTORY_WRONGS),
            )
            for history in HISTORIES
        )
        return contextual_scenario_question(
            rng, bank,
            hint=("การวิเคราะห์ที่ดีบอกทั้งปัญหาหรือความต้องการที่ผลักดันการเปลี่ยนแปลง "
                  "และความรู้ทางวิทยาศาสตร์หรือคณิตศาสตร์ที่ทำให้เปลี่ยนได้"),
            topic=LINK_TOPIC,
        )
