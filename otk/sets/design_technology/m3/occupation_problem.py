@question_type(
    "tech.occupation_problem_foundation",
    display_name={"th": "จำแนกประเภทของทรัพย์สินทางปัญญา"},
    level=M3, subject=SUBJECT, topic=IP_TOPIC,
)
class OccupationProblemFoundation(QuestionType):
    def build(self, rng: Random, **params):
        item, kind = rng.choice(IP_ITEMS)
        if rng.random() < 0.5:
            return _labelled(stem=f"“{item}” ได้รับความคุ้มครองทางทรัพย์สินทางปัญญาในรูปแบบใด",
                             correct=kind, wrongs=tuple(k for k in IP_KINDS if k != kind),
                             hint=IP_HINT, topic=IP_TOPIC)
        others = [i for i, k in IP_ITEMS if k != kind]
        return _labelled(stem=f"ข้อใดได้รับความคุ้มครองในรูปแบบ{kind}",
                         correct=item, wrongs=tuple(others), hint=IP_HINT, topic=IP_TOPIC)


