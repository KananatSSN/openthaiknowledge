@question_type(
    "tech.test_reasoning_foundation",
    display_name={"th": "วิเคราะห์แนวโน้มจากตารางผลการทดสอบ"},
    level=M3, subject=SUBJECT, topic=ANALYSIS_TOPIC,
)
class TestReasoningFoundation(QuestionType):
    def build(self, rng: Random, **params):
        x_name, x_unit, y_name, y_unit = rng.choice(EXPERIMENTS)
        xs = sorted(rng.sample(range(1, 11), 4))
        shape = rng.choice((UP, DOWN, SAME, PEAK))
        base = rng.randint(20, 60)
        steps = [rng.randint(3, 12) for _ in range(3)]
        if shape == UP:
            ys = [base, base + steps[0], base + steps[0] + steps[1], base + sum(steps)]
        elif shape == DOWN:
            ys = [base + sum(steps), base + steps[0] + steps[1], base + steps[0], base]
        elif shape == SAME:
            ys = [base] * 4
        else:
            ys = [base, base + steps[0] + steps[1], base + steps[0], base - steps[2] if base > steps[2] else base // 2]
        rows = " ".join(f"{x_name} {x} {x_unit} ได้ {y} {y_unit}" for x, y in zip(xs, ys))
        return _labelled(
            stem=f"ผลการทดสอบ {rows} ข้อใดสรุปแนวโน้มได้ถูกต้อง",
            correct=f"เมื่อ{x_name}เพิ่มขึ้น {y_name}{shape}",
            wrongs=tuple(f"เมื่อ{x_name}เพิ่มขึ้น {y_name}{s}" for s in (UP, DOWN, SAME, PEAK) if s != shape),
            hint="เรียงผลตามค่าที่เปลี่ยน แล้วดูว่าผลเพิ่ม ลด คงที่ หรือเพิ่มแล้วลดลง",
            topic=ANALYSIS_TOPIC,
        )


@question_type(
    "tech.test_reasoning_fluency",
    display_name={"th": "คำนวณร้อยละของการปรับปรุงจากผลการทดสอบ"},
    level=M3, subject=SUBJECT, topic=ANALYSIS_TOPIC,
)
class TestReasoningFluency(QuestionType):
    def build(self, rng: Random, **params):
        before = rng.choice((20, 25, 40, 50, 80))
        percent = rng.choice([p for p in range(10, 101, 5) if before * p % 100 == 0])
        after = before + before * percent // 100
        return _labelled(
            stem=(f"ก่อนปรับปรุง สะพานรับน้ำหนักได้ {before} นิวตัน หลังปรับปรุงรับได้ {after} นิวตัน "
                  f"ความสามารถในการรับน้ำหนักเพิ่มขึ้นร้อยละเท่าใด"),
            correct=f"ร้อยละ {percent}",
            wrongs=tuple(f"ร้อยละ {w}" for w in rng.sample(
                _near(percent, (after - before, (after - before) * 100 // after, percent + 10, 100 + percent)), 3)),
            hint="ร้อยละที่เพิ่มขึ้น = (ค่าหลัง − ค่าก่อน) ÷ ค่าก่อน × 100",
            topic=ANALYSIS_TOPIC,
        )


