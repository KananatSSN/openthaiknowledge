@question_type(
    "tech.constrained_testing_foundation",
    display_name={"th": "ตรวจผลการทดสอบกับกรอบเงื่อนไข"},
    level=M2, subject=SUBJECT, topic=CHECK_TOPIC,
)
class ConstrainedTestingFoundation(QuestionType):
    """Three conditions, one prototype's results; name the one it fails, if any."""

    def build(self, rng: Random, **params):
        load, price, width = rng.randrange(2, 11), rng.randrange(150, 401, 50), rng.randrange(30, 61, 5)
        conditions = {
            "รับน้ำหนัก": f"รับน้ำหนักได้อย่างน้อย {load} กิโลกรัม",
            "ราคา": f"ราคาไม่เกิน {price} บาท",
            "ความกว้าง": f"กว้างไม่เกิน {width} เซนติเมตร",
        }
        fail = rng.choice(["รับน้ำหนัก", "ราคา", "ความกว้าง", None])
        got_load = load - rng.randint(1, 2) if fail == "รับน้ำหนัก" else load + rng.randint(0, 3)
        got_price = price + rng.randrange(10, 60, 10) if fail == "ราคา" else price - rng.randrange(0, 60, 10)
        got_width = width + rng.randint(2, 8) if fail == "ความกว้าง" else width - rng.randint(0, 8)
        correct = ALL_PASS if fail is None else f"ไม่ผ่านเงื่อนไขเรื่อง{fail}"
        choices = [ALL_PASS, *(f"ไม่ผ่านเงื่อนไขเรื่อง{c}" for c in conditions)]
        return _labelled(
            stem=(f"เงื่อนไขของชั้นวางของคือ {' '.join(conditions.values())} "
                  f"ผลการทดสอบชิ้นงาน รับน้ำหนักได้ {got_load} กิโลกรัม ราคา {got_price} บาท "
                  f"กว้าง {got_width} เซนติเมตร ข้อใดถูกต้อง"),
            correct=correct, wrongs=tuple(c for c in choices if c != correct),
            hint="ตรวจผลทีละเงื่อนไข อย่างน้อยหมายถึงเท่ากับหรือมากกว่า ไม่เกินหมายถึงเท่ากับหรือน้อยกว่า",
            topic=CHECK_TOPIC,
        )


@question_type(
    "tech.constrained_testing_fluency",
    display_name={"th": "ออกแบบการทดสอบเปรียบเทียบให้ยุติธรรม"},
    level=M2, subject=SUBJECT, topic=CHECK_TOPIC,
)
class ConstrainedTestingFluency(QuestionType):
    def build(self, rng: Random, **params):
        what, constant, wrongs = rng.choice(FAIR_TESTS)
        return _labelled(
            stem=f"ต้องการ{what}ให้ยุติธรรม ต้องควบคุมสิ่งใดให้เหมือนกัน",
            correct=constant, wrongs=tuple(wrongs),
            hint="สิ่งที่ต้องควบคุมคือทุกอย่างที่อาจมีผลต่อผล ยกเว้นสิ่งที่ต้องการเปรียบเทียบ และไม่ใช่ผลที่วัดได้",
            topic=CHECK_TOPIC,
        )


