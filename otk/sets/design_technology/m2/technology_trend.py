@question_type(
    "tech.technology_trend_foundation",
    display_name={"th": "จำแนกผลกระทบของเทคโนโลยีต่อชีวิต สังคม และสิ่งแวดล้อม"},
    level={"th": "ม.2"}, subject=SUBJECT, topic=TREND_TOPIC,
)
class TechnologyTrendFoundation(QuestionType):
    """Pick the effect of a technology on one named side of life."""

    def build(self, rng: Random, **params):
        effect = rng.choice(EFFECTS)
        side = rng.choice(SIDES)
        wrongs = [effect.of(other) for other in SIDES if other != side]
        stranger = rng.choice([e for e in EFFECTS if e.technology != effect.technology])
        wrongs.append(stranger.of(rng.choice([s for s in SIDES if s != side])))
        return _labelled(
            stem=f"ข้อใดเป็นผลกระทบด้าน{side}ของ{effect.technology}",
            correct=effect.of(side), wrongs=tuple(wrongs),
            hint=("ด้านชีวิตความเป็นอยู่คือผลต่อตัวผู้ใช้ ด้านสังคมคือผลต่อชุมชน อาชีพ "
                  "และความสัมพันธ์ของผู้คน ด้านสิ่งแวดล้อมคือผลต่อขยะ มลพิษ และทรัพยากร"),
            topic=TREND_TOPIC,
        )


