@question_type(
    "tech.materials_tools_foundation",
    display_name={"th": "เลือกวัสดุให้เหมาะกับงานตามสมบัติของวัสดุ"},
    level=M1, subject=SUBJECT, topic=TOOLS_TOPIC,
)
class MaterialsToolsFoundation(QuestionType):
    def build(self, rng: Random, **params):
        need, material = rng.choice(MATERIAL_NEEDS)
        return _labelled(
            stem=f"ต้องการวัสดุสำหรับ{need} ควรเลือกวัสดุใด",
            correct=material, wrongs=tuple([m for m in MATERIALS if m != material]),
            hint="พิจารณาสมบัติที่งานต้องการ เช่น นำไฟฟ้า เป็นฉนวน ยืดหยุ่น โปร่งใส ทนความร้อน หรือแข็งแรง",
            topic=TOOLS_TOPIC,
        )


@question_type(
    "tech.materials_tools_fluency",
    display_name={"th": "เลือกเครื่องมือให้เหมาะกับงาน"},
    level=M1, subject=SUBJECT, topic=TOOLS_TOPIC,
)
class MaterialsToolsFluency(QuestionType):
    def build(self, rng: Random, **params):
        index = rng.randrange(len(TOOLS))
        tool, job = TOOLS[index]
        others = rng.sample([row for i, row in enumerate(TOOLS) if i != index], 3)
        hint = "นึกถึงลักษณะของเครื่องมือ ใบเลื่อยตัด ดอกสว่านเจาะ ปลายไขควงขันสกรู หัวแร้งให้ความร้อนหลอมตะกั่ว"
        if rng.random() < 0.5:
            return _labelled(stem=f"ถ้าต้องการ{job} ควรใช้เครื่องมือใด",
                             correct=tool, wrongs=tuple(t for t, _ in others), hint=hint, topic=TOOLS_TOPIC)
        return _labelled(stem=f"{tool}ใช้ทำงานใด",
                         correct=job, wrongs=tuple(j for _, j in others), hint=hint, topic=TOOLS_TOPIC)


@question_type(
    "tech.materials_tools_application",
    display_name={"th": "คำนวณการทำงานของเฟืองและใช้เครื่องมืออย่างปลอดภัย"},
    level=M1, subject=SUBJECT, topic=TOOLS_TOPIC,
)
class MaterialsToolsApplication(QuestionType):
    def build(self, rng: Random, **params):
        if rng.random() < 0.5:
            return _situation(rng, SAFE_USE, topic=TOOLS_TOPIC,
                              hint="การใช้เครื่องมือให้ปลอดภัยคือยึดชิ้นงานให้มั่น ป้องกันตาและมือ และเก็บเครื่องมืออย่างถูกวิธี")
        driver = rng.choice((10, 12, 15, 20, 24, 30, 40))
        driven = rng.choice([t for t in (10, 12, 15, 20, 24, 30, 40, 60) if t != driver])
        turns = rng.randint(2, 12)
        while turns * driver % driven:
            turns += 1
        answer = turns * driver // driven
        wrongs = _near(answer, (turns * driven // driver if turns * driven % driver == 0 else turns + 1,
                                turns, turns * driver, answer * 2))
        return _labelled(
            stem=(f"เฟืองขับมี {driver} ฟัน ขบกับเฟืองตามที่มี {driven} ฟัน "
                  f"ถ้าเฟืองขับหมุน {turns} รอบ เฟืองตามจะหมุนกี่รอบ"),
            correct=f"{answer} รอบ", wrongs=tuple(f"{w} รอบ" for w in rng.sample(wrongs, 3)),
            hint="ฟันที่เคลื่อนผ่านจุดขบกันของทั้งสองเฟืองมีจำนวนเท่ากัน รอบของเฟืองตาม = รอบของเฟืองขับ × ฟันเฟืองขับ ÷ ฟันเฟืองตาม",
            topic=TOOLS_TOPIC,
        )
