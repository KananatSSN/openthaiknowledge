@question_type(
    "tech.problem_finding_application",
    display_name={"th": "เลือกข้อมูลที่จำเป็นต่อการแก้ปัญหา"},
    level=M1, subject=SUBJECT, topic=PROBLEM_TOPIC,
)
class ProblemFindingApplication(QuestionType):
    def build(self, rng: Random, **params):
        thing, needed, not_needed = rng.choice(INFORMATION)
        facts = list(not_needed)
        rng.shuffle(facts)
        pairs = tuple(f"{a}และ{b}" for a, b in zip(facts[::2], facts[1::2]))
        return _labelled(
            stem=f"ในการออกแบบ{thing} ข้อมูลชุดใดจำเป็นต้องรวบรวมมากที่สุด",
            correct=needed, wrongs=pairs,
            hint="ข้อมูลที่จำเป็นคือข้อมูลที่เปลี่ยนขนาด รูปร่าง หรือการทำงานของชิ้นงานได้จริง",
            topic=PROBLEM_TOPIC,
        )


