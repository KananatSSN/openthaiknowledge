@question_type(
    "tech.problem_finding_foundation",
    display_name={"th": "ขั้นตอนของกระบวนการออกแบบเชิงวิศวกรรม"},
    level=M1, subject=SUBJECT, topic=PROBLEM_TOPIC,
)
class ProblemFindingFoundation(QuestionType):
    def build(self, rng: Random, **params):
        if rng.random() < 0.6:
            step = rng.randrange(6)
            activity = rng.choice(ACTIVITIES[step])
            others = [s for i, s in enumerate(DESIGN_STEPS) if i != step]
            return _labelled(
                stem=f"“{activity}” อยู่ในขั้นตอนใดของกระบวนการออกแบบเชิงวิศวกรรม",
                correct=DESIGN_STEPS[step], wrongs=tuple(others),
                hint=STEPS_HINT, topic=PROBLEM_TOPIC,
            )
        index = rng.randrange(5)
        others = [s for i, s in enumerate(DESIGN_STEPS) if i not in (index, index + 1)]
        return _labelled(
            stem=f"ในกระบวนการออกแบบเชิงวิศวกรรม ขั้นตอนที่ทำต่อจาก “{DESIGN_STEPS[index]}” คือขั้นตอนใด",
            correct=DESIGN_STEPS[index + 1], wrongs=tuple(others),
            hint=STEPS_HINT, topic=PROBLEM_TOPIC,
        )


