# ══ ว 1.3 ม.3/2 — การถ่ายทอดลักษณะเดียวที่เด่นข่มด้อยอย่างสมบูรณ์ ═════════════════


class MendelTrait(NamedTuple):
    """One trait with a dominant and a recessive form, and its symbol."""
    subject: str
    letter: str
    dominant: str
    recessive: str


MENDEL_TRAITS = (
    MendelTrait("ต้นถั่ว", "T", "ต้นสูง", "ต้นเตี้ย"),
    MendelTrait("ดอกถั่ว", "P", "ดอกสีม่วง", "ดอกสีขาว"),
    MendelTrait("เมล็ดถั่ว", "R", "เมล็ดกลม", "เมล็ดย่น"),
    MendelTrait("หนู", "S", "ขนสั้น", "ขนยาว"),
)


def _genotypes(trait: MendelTrait) -> tuple[str, str, str]:
    upper, lower = trait.letter, trait.letter.lower()
    return (upper + upper, upper + lower, lower + lower)


