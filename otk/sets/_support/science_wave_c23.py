def _borrowed(rng: Random, hazard: str) -> Plan:
    plan = PLANS[hazard]
    monitor, conduct = MORE_PLAN_LINES[hazard]
    return Plan(rng.choice((plan.monitor, monitor)), rng.choice((plan.conduct, conduct)))


def _plan(plan: Plan) -> str:
    return f"เฝ้าระวังโดย{plan.monitor} และปฏิบัติตนให้ปลอดภัยโดย{plan.conduct}"


def plan_item(rng: Random, hazard: str, topic: str) -> GeneratedQuestion:
    """Monitoring and safe conduct for a case; a wrong choice takes a half elsewhere."""
    plan = PLANS[hazard]
    first, second = [_borrowed(rng, other) for other in PLANS if other != hazard]
    if rng.random() < 0.5:
        first, second = second, first
    return _labelled(
        stem=f"{rng.choice(CASES[hazard])} ซึ่งเสี่ยงต่อ{hazard} "
             "ควรออกแบบแนวทางการเฝ้าระวังและการปฏิบัติตนให้ปลอดภัยอย่างไรจึงเหมาะสมที่สุด",
        correct=_plan(plan),
        wrongs=(_plan(Plan(first.monitor, plan.conduct)),
                _plan(Plan(plan.monitor, first.conduct)),
                _plan(second),
                # Both halves from elsewhere, crossed: wrong in both, so the
                # answer is not the choice every wrong shares a half with.
                _plan(Plan(first.monitor, second.conduct)),
                _plan(Plan(second.monitor, first.conduct))),
        hint="ตรวจทั้งสองส่วนว่าตรงกับภัยในเรื่อง: สัญญาณที่ต้องเฝ้าดู และวิธีหลบให้พ้นอันตราย",
        topic=topic,
    )


def explanation_item(rng: Random, hazard: str, topic: str) -> GeneratedQuestion:
    """Every named object explained; each wrong choice makes one of them false."""
    parts = EXPLANATIONS[hazard]

    def line(false_index: int | None) -> str:
        return " / ".join(
            f"{part.label}: "
            f"{rng.choice((part.false, *MORE_FALSES[hazard, part.label])) if i == false_index else part.true}"
            for i, part in enumerate(parts))

    falsified = rng.sample(range(len(parts)), 3)
    names = [part.label for part in parts]
    labels = " ".join(names[:-1]) + " และ" + names[-1]
    return _labelled(
        stem=f"ข้อใดอธิบาย{labels}ของ{hazard}ได้ถูกต้องทั้งหมด",
        correct=line(None),
        wrongs=tuple(line(index) for index in falsified),
        hint="ตรวจทีละส่วน ข้อที่ผิดจะผิดอย่างน้อยหนึ่งส่วน",
        topic=topic,
    )


