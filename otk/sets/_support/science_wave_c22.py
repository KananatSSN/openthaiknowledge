from __future__ import annotations

from random import Random

from otk.core.question import GeneratedQuestion
from otk.kit.concept_bank import more_wrongs
from otk.sets._support.science_wave_b14 import _labelled
from otk.sets._support.science_wave_c13 import _swapped, _swaps
from otk.sets._support.science_wave_c15 import FIVE_LETTERS


def _match(names: list[str], letters: list[str]) -> str:
    return " / ".join(f"{name} → {letter}" for name, letter in zip(names, letters))


def _matching_item(rng: Random, names: list[str], descriptions: list[str], *,
                   intro: str, question: str, hint: str, topic: str) -> GeneratedQuestion:
    """Five descriptions lettered in shuffled order; the answer places all five."""
    order = list(range(len(names)))
    rng.shuffle(order)
    listing = " / ".join(f"{FIVE_LETTERS[pos]}. {descriptions[i]}" for pos, i in enumerate(order))
    letter_of = {i: FIVE_LETTERS[pos] for pos, i in enumerate(order)}
    right = [letter_of[i] for i in range(len(names))]
    return _labelled(
        stem=f"{intro} — {listing} {question}",
        correct=_match(names, right),
        wrongs=tuple(_match(names, _swapped(right, i, j)) for i, j in _swaps(rng, 3, len(names))),
        hint=hint,
        topic=topic,
    )


