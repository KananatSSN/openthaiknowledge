"""Wave C, slice 17 — weather, storms and forecasting, at ม.1.

* ``ว 3.2 ม.1/2`` ปัจจัยที่มีผลต่อการเปลี่ยนแปลงองค์ประกอบของลมฟ้าอากาศ — all three stages
* ``ว 3.2 ม.1/3`` พายุฝนฟ้าคะนองและพายุหมุนเขตร้อน — all three stages
* ``ว 3.2 ม.1/4`` การพยากรณ์อากาศ — all three stages

``ม.1/2`` names ``จากข้อมูลที่รวบรวมได้``, so its one ``exact`` set, Fluency,
answers from a weather record printed in the stem — a day's readings, or the
pressure at two places — and the test re-derives each answer from the numbers.

``ม.1/3`` joins ``เปรียบเทียบกระบวนการเกิด…และผลที่มีต่อสิ่งมีชีวิตและสิ่งแวดล้อม``
with ``นำเสนอแนวทางการปฏิบัติตนให้เหมาะสมและปลอดภัย``. Both are assessable, so
Foundation (the practice that fits a storm case) and Fluency (the comparison) are
``exact``. The comparison names two storms and both their formation and their
effects, so every Fluency answer states all four, and each wrong choice gets one
half of it the wrong way round.

``ม.1/4`` joins ``อธิบายการพยากรณ์อากาศ`` with ``พยากรณ์อากาศอย่างง่ายจากข้อมูล``, two
free verbs, so Foundation (how a forecast is made) and Fluency (making one from a
record whose trends decide it) are both ``exact``.
"""

