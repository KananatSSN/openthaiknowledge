"""Wave B — the ม.1 cell block, ``ว 1.2``.

``ว 1.2`` is the largest untouched block in the curriculum: 47 indicators from
ป.1 to ม.4 with no sets at all before this. It opens here at ม.1, where the
cell is introduced.

Slice 4:

* ``ว 1.2 ม.1/1`` เซลล์พืชและเซลล์สัตว์ — all three stages
* ``ว 1.2 ม.1/3`` รูปร่างของเซลล์กับการทำหน้าที่ — all three stages

The two are one idea taken twice: ม.1/1 asks what each part of a cell does, and
ม.1/3 asks why a whole cell is shaped the way it is. Both are answered from the
same two tables below, so a structure's job cannot be stated one way in one set
and another way in the other.
"""

from __future__ import annotations

from typing import NamedTuple

from otk.core.content import text
from otk.core.distractors import label_pool
from otk.core.question import GeneratedQuestion
from otk.kit.concept_bank import more_wrongs

SUBJECT = "ชีวะ"
TOPIC = "เซลล์และการดำรงชีวิต"
LEVEL = {"th": "ม.1"}

# Where a structure is found. ``ม.1/1`` names no animal-only structure, which
# is itself the point of the comparison.
PLANT_ONLY = "เซลล์พืชเท่านั้น"
BOTH = "พบได้ทั้งเซลล์พืชและเซลล์สัตว์"


def _labelled(*, stem: str, correct: str, wrongs: tuple[str, ...],
              hint: str) -> GeneratedQuestion:
    """A question whose choices are all Thai labels drawn from one pool."""
    return GeneratedQuestion(
        stem=[text(stem)],
        correct=[text(correct)],
        distractors=label_pool([correct, *wrongs]),
        topic=TOPIC,
        hint=[text(hint)],
    )


