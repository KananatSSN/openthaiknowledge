"""Wave B — the ม.1 plant reproduction pair, ``ว 1.2``.

* ``ว 1.2 ม.1/11`` การสืบพันธุ์ของพืชดอก — all three stages
* ``ว 1.2 ม.1/12`` โครงสร้างดอกและการเกิดผลและเมล็ด — all three stages

``ม.1/11`` has two modes and ``ม.1/12``'s pollination half has two agents, so
neither may be asked as "which of the two is it" — that offers two choices, which
is not a question. Both are asked as four *statements*, where every wrong one is
a true fact about the other mode or the other agent.
"""

from __future__ import annotations

from random import Random

from otk.core.content import text
from otk.core.distractors import label_pool
from otk.core.question import GeneratedQuestion
from otk.kit.concept_bank import more_wrongs

SUBJECT = "ชีวะ"
TOPIC = "การดำรงชีวิตของพืช"
LEVEL = {"th": "ม.1"}


def _labelled(*, stem: str, correct: str, wrongs: tuple[str, ...],
              hint: str) -> GeneratedQuestion:
    """A question whose choices are all Thai labels drawn from one pool."""
    return GeneratedQuestion(
        stem=[text(stem)],
        correct=[text(correct)],
        distractors=label_pool([correct, *wrongs]),
        topic=TOPIC,
        hint=[text(hint)],
    )


def _statement_question(*, subject: str, mine: list[str], theirs: list[str],
                        rng: Random, hint: str) -> GeneratedQuestion:
    """Pick the true statement about ``subject`` from four.

    The three wrong ones are true statements about its counterpart, so the item
    turns on attaching the fact to the right thing rather than on spotting an
    invented one.
    """
    rng.shuffle(theirs)
    return _labelled(
        stem=f"ข้อใดกล่าวถึง “{subject}” ได้ถูกต้อง",
        correct=rng.choice(mine),
        wrongs=tuple(theirs[:3]),
        hint=hint,
    )


