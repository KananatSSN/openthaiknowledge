"""Wave B — the ม.3 ecology block, ``ว 1.1``.

Biological science was the thinnest area in the catalog: seven sets, of which
only `ว 1.1 ป.5/3` โซ่อาหาร had a three-stage path. Wave B starts where Wave A
did, by finishing the topics that already exist before opening new ones.

Slice 1 — topics that already had a Foundation set and nothing above it:

* ``ว 1.1 ม.3/1`` องค์ประกอบและระดับของระบบนิเวศ — Fluency and Application
* ``ว 1.1 ม.3/2`` ความสัมพันธ์ระหว่างสิ่งมีชีวิต — Fluency and Application

Both of those indicators say ``ที่ได้จากการสำรวจ`` — the learner is meant to
reason from what a survey found, not to recite a definition, so both Application
sets state an observation and ask what it implies.

Slice 2 — topics with no sets at all:

* ``ว 1.1 ม.3/3`` สายใยอาหารและการถ่ายทอดพลังงาน — all three stages
* ``ว 1.1 ม.3/4`` บทบาทของผู้ผลิต ผู้บริโภค และผู้ย่อยสลาย — all three stages

The ป.5 pilot sets work a single linear chain, where every organism has one food
and one predator. ม.3 works a *web*, where most have several, and asks about the
energy that moves along it. That difference is what slice 2 is built on.
"""

