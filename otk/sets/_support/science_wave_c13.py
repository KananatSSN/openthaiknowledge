"""Wave C, slice 13 — what water vapour becomes, and what falls from clouds, at ป.5.

* ``ว 3.2 ป.5/4`` การเกิดเมฆ หมอก น้ำค้าง และน้ำค้างแข็ง — all three stages
* ``ว 3.2 ป.5/5`` การเกิดฝน หิมะ และลูกเห็บ — all three stages

Both turn on ``เปรียบเทียบ``, so by the sorting-verb rule each has one ``exact``
set, at Fluency. Each also names several objects under that one verb — four in
``ป.5/4``, three in ``ป.5/5`` — so by the multi-object rule every answer the
``exact`` set accepts compares all of them, and each wrong choice swaps two.

``ป.5/4`` names its evidence as ``จากแบบจำลอง``, so its Fluency stem carries the
four classroom models. ``ป.5/5`` names ``จากข้อมูลที่รวบรวมได้``, so its Fluency
stem carries a record of three reported events, shuffled per draw, and the
answer is re-derived from where each event landed in the record.
"""

from __future__ import annotations

from random import Random

from otk.kit.concept_bank import more_wrongs


def _swaps(rng: Random, count: int, size: int) -> list[tuple[int, int]]:
    pairs = [(i, j) for i in range(size) for j in range(i + 1, size)]
    rng.shuffle(pairs)
    return pairs[:count]


def _swapped(items: list, first: int, second: int) -> list:
    out = list(items)
    out[first], out[second] = out[second], out[first]
    return out


