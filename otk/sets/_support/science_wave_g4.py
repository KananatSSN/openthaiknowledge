"""Wave G, slice 4 — วิทยาศาสตร์ วิธีการทางวิทยาศาสตร์ และทักษะกระบวนการ (ม.1 บทนำ).

Searching the whole registry returned **nothing** for ``วิธีการทางวิทยาศาสตร์``,
``ทักษะกระบวนการ`` or ``สมมติฐาน``, at any level. The nearest existing sets are
two that identify variables *inside* a content experiment —
``phys.friction_factor_foundation`` and ``body.heart_rate_experiment_fluency`` —
and both are filed under their content indicator, because that is what they are
about. The skill itself had no home.

**These sets carry no indicator code.** All 52 ``ม.1`` rows in
``science_ipst_outcomes.csv`` were checked and none names these skills; the only
four rows in the entire curriculum that mention ``สมมติฐาน`` or
``ทักษะกระบวนการ`` are ``ม.4``/``ม.6`` เพิ่มเติม courses. That matches IPST's own
structure — บทนำ "การเรียนรู้วิทยาศาสตร์" deliberately carries no ตัวชี้วัด, and
the skills are then exercised by the content indicators for the rest of the year.
So every set here is ``outside_scope`` with empty ``indicator_codes``, the filing
seventeen existing sets already use for taught content the curriculum does not
enumerate.

**And they carry a sixth subject, ``วิทยาศาสตร์ทั่วไป``.** Process skills are not
ฟิสิกส์, เคมี, ชีวะ, ธรณีวิทยา or ดาราศาสตร์; filing them under one of those
would put ``ตัวแปรต้น`` in front of a learner who asked for physics. The subject
is published in the catalog, so this is a learner-facing addition, made
deliberately. ``test_science_stage_registry.py`` derives its subject list from
the registry precisely so that a new subject has to be added there by name.

Two units, seven sets:

* ``sci.scientific_method_*`` — the steps in order and what each is for, writing
  a hypothesis that can actually be tested, and criticising an investigation.
* ``sci.process_skill_*`` — naming a skill, separating การสังเกต from
  การลงความเห็น, identifying ตัวแปรต้น/ตัวแปรตาม/ตัวแปรควบคุม, and reading a
  drawn results chart.

Only the last is drawn, and it is drawn because ``การตีความหมายข้อมูล`` is a skill
about a graph. The other five are about what a learner *says* and *decides*, and a
picture beside them would be decoration.
"""

