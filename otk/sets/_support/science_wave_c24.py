"""Wave C, slice 24 — solar energy, pressure-driven circulation and the Coriolis effect, at ม.6.

* ``ว 3.2 ม.6/7`` ปัจจัยที่มีผลต่อการได้รับพลังงานจากดวงอาทิตย์ — all three stages
* ``ว 3.2 ม.6/8`` การหมุนเวียนของอากาศจากความแตกต่างของความกดอากาศ — all three stages
* ``ว 3.2 ม.6/9`` ทิศทางการเคลื่อนที่ของอากาศจากการหมุนรอบตัวเองของโลก — all three stages

Each indicator is a single ``อธิบาย``, so each earns one ``exact`` set, at
Fluency. ``ม.6/7`` names the factors as a class, so its answer explains all four
and every wrong choice makes exactly one false. ``ม.6/8`` reads a temperature
record and explains the whole cell — pressure, rising and sinking, the surface
wind and the return flow aloft — each wrong choice reversing one part. ``ม.6/9``
gives a hemisphere and a direction of travel and asks where the air turns.
Foundation takes one idea at a time and is ``standard_scope``.
"""

from __future__ import annotations

from random import Random

from otk.core.question import GeneratedQuestion
from otk.kit.concept_bank import more_wrongs
from otk.sets._support.science_wave_b14 import _labelled
from otk.sets._support.science_wave_c23 import Part

# Extra false readings, keyed by a part's own false reading. A part listed here
# can be falsified in more than one way; parts not listed keep their one false.
MORE_PART_FALSES: dict[str, tuple[str, ...]] = {}


def part_false(rng: Random, part: Part) -> str:
    return rng.choice((part.false, *MORE_PART_FALSES.get(part.false, ())))


def parts_item(rng: Random, parts: tuple[Part, ...], *, stem: str, hint: str,
               topic: str) -> GeneratedQuestion:
    """Every part stated truly; each wrong choice makes exactly one part false."""

    def line(false_index: int | None) -> str:
        return " / ".join(f"{part.label}: {part_false(rng, part) if i == false_index else part.true}"
                          for i, part in enumerate(parts))

    return _labelled(
        stem=stem,
        correct=line(None),
        wrongs=tuple(line(index) for index in rng.sample(range(len(parts)), 3)),
        hint=hint,
        topic=topic,
    )


