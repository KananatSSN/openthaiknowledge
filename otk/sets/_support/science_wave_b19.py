from __future__ import annotations

from random import Random
from typing import NamedTuple

from otk.core.question import GeneratedQuestion
from otk.kit.concept_bank import more_wrongs
from otk.sets._support.science_wave_b14 import _labelled

UPPER_FOUR = {"th": "ม.4"}
BALANCE_TOPIC = "การรักษาดุลยภาพของร่างกาย"


class Fact(NamedTuple):
    """One question with a single answer, drawn against the other answers."""
    question: str
    answer: str


def _fact_question(rng: Random, facts: tuple[Fact, ...], *, hint: str,
                   topic: str) -> GeneratedQuestion:
    item = rng.choice(facts)
    others = [other.answer for other in facts if other.answer != item.answer]
    rng.shuffle(others)
    return _labelled(stem=item.question, correct=item.answer,
                     wrongs=tuple(others[:3]), hint=hint, topic=topic)


