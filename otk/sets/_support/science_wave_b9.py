"""Wave B — the ม.2 excretory block and the first two care indicators, ``ว 1.2``.

* ``ว 1.2 ม.2/3`` การดูแลรักษาระบบหายใจ — all three stages
* ``ว 1.2 ม.2/4`` อวัยวะในระบบขับถ่ายและการกำจัดของเสียทางไต — all three stages
* ``ว 1.2 ม.2/5`` การดูแลรักษาระบบขับถ่าย — all three stages

``ม.2`` has six ``ตระหนัก`` indicators and they are not all alike. What decides
the filing here is the *evidence clause* the indicator itself names, not the word
``ตระหนัก``:

* ``ม.2/3`` and ``ม.2/5`` say ``โดยการบอกแนวทาง…``. Stating the แนวทาง is exactly
  what a multiple-choice item does, so the Fluency set — the one that asks for the
  แนวทาง fitting a situation — is filed ``exact``.
* Indicators whose evidence clause is an action (``โดยการดูแลรักษาร่างกาย``,
  ``โดยการประพฤติตนให้เหมาะสม``, ``โดยมีส่วนร่วมในการดูแลรักษา``) are never
  ``exact`` here, because the evidence is conduct and no item can observe it.

Foundation and Application remain ``standard_scope`` in a ``ตระหนัก`` topic even
under the first rule: knowing a reason and analysing a case are within the
standard, but they are not the ``บอกแนวทาง`` the indicator asks for.

The care machinery below (``Care``, ``Need``, ``care_foundation``,
``care_fluency``) is shared with the later ม.2 care topics, which are built the
same way.
"""

from __future__ import annotations

from random import Random
from typing import NamedTuple

from otk.core.content import text
from otk.core.distractors import label_pool
from otk.core.question import GeneratedQuestion
from otk.kit.concept_bank import contextual_scenario_question, more_wrongs

SUBJECT = "ชีวะ"
TOPIC = "ระบบต่าง ๆ ในร่างกายมนุษย์"
LEVEL = {"th": "ม.2"}


def labelled(*, stem: str, correct: str, wrongs: tuple[str, ...],
             hint: str) -> GeneratedQuestion:
    """A question whose choices are all Thai labels drawn from one pool."""
    return GeneratedQuestion(
        stem=[text(stem)],
        correct=[text(correct)],
        distractors=label_pool([correct, *wrongs]),
        topic=TOPIC,
        hint=[text(hint)],
    )


def scenario_question(rng: Random, bank: tuple, *, hint: str) -> GeneratedQuestion:
    """Draw one authored (สถานการณ์, ข้อสรุป, ตัวลวง) row."""
    return contextual_scenario_question(
        rng, bank, hint=hint, topic=TOPIC,
    )


# ══ machinery shared by every ตระหนัก…บอกแนวทาง topic in ม.2 ═══════════════════

class Care(NamedTuple):
    """One way of looking after a system, and why it works."""
    practice: str
    reason: str


class Need(NamedTuple):
    """A situation, and the practice from the same table that answers it."""
    situation: str
    practice: str


def care_foundation(rng: Random, *, system: str, cares: tuple[Care, ...],
                    hint: str) -> GeneratedQuestion:
    """Match a practice to its reason, in either direction."""
    item = rng.choice(cares)
    others = [other for other in cares if other.practice != item.practice]
    rng.shuffle(others)
    if rng.random() < 0.5:
        return labelled(
            stem=f"การ “{item.practice}” ช่วยให้{system}ทำงานเป็นปกติได้อย่างไร",
            correct=item.reason,
            wrongs=tuple(other.reason for other in others[:3]),
            hint=hint,
        )
    return labelled(
        stem=f"แนวทางใดในการดูแล{system}อาศัยเหตุผลที่ว่า {item.reason}",
        correct=item.practice,
        wrongs=tuple(other.practice for other in others[:3]),
        hint=hint,
    )


def care_fluency(rng: Random, *, needs: tuple[Need, ...], cares: tuple[Care, ...],
                 hint: str) -> GeneratedQuestion:
    """State the แนวทาง that fits the situation — the indicator's own evidence."""
    need = rng.choice(needs)
    others = [care.practice for care in cares if care.practice != need.practice]
    rng.shuffle(others)
    return labelled(
        stem=need.situation,
        correct=need.practice,
        wrongs=tuple(others[:3]),
        hint=hint,
    )


