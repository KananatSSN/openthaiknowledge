def _moon_question(
    *, stem: str, correct: str, wrongs: tuple[str, ...], hint: str,
) -> GeneratedQuestion:
    return GeneratedQuestion(
        stem=[text(stem)],
        correct=[text(correct)],
        distractors=label_pool([correct, *wrongs]),
        topic=SPACE,
        hint=[text(hint)],
    )


def _clock(minutes: int) -> str:
    minutes %= 24 * 60
    return f"{minutes // 60:02d}:{minutes % 60:02d} น."


@question_type(
    "astro.moon_phase_foundation",
    display_name={"th": "ข้างขึ้นข้างแรม: ระบุตำแหน่งและสาเหตุ"},
    level={"th": "ม.3"}, subject=ASTRONOMY, topic=SPACE,
)
class MoonPhaseFoundation(QuestionType):
    """Name the phase from one stated geometry or calendar day, or its cause."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        which = rng.randrange(3)
        if which == 0:
            position, phase = rng.choice(MOON_GEOMETRY)
            wrongs = tuple(name for name in MOON_PHASES if name != phase)
            return _moon_question(
                stem=f"จากแบบจำลองดวงอาทิตย์–โลก–ดวงจันทร์ ถ้า{position} คนบนโลกจะเห็นดวงจันทร์แบบใด",
                correct=phase,
                wrongs=wrongs,
                hint="ดวงจันทร์สว่างครึ่งดวงเสมอ ให้ดูว่าด้านสว่างหันมาทางโลกมากน้อยเพียงใด",
            )
        if which == 1:
            day, phase = rng.choice(MOON_CALENDAR)
            wrongs = tuple(name for name in MOON_PHASES if name != phase)
            return _moon_question(
                stem=f"คืนวัน{day}ตามปฏิทินจันทรคติ ตรงกับดวงจันทร์ในลักษณะใด",
                correct=phase,
                wrongs=wrongs,
                hint="ขึ้น 15 ค่ำคือเต็มดวง แรม 15 ค่ำคือจันทร์ดับ ส่วน 8 ค่ำคือครึ่งดวง",
            )
        question, correct, wrongs = rng.choice(MOON_CAUSE_FACTS)
        return _moon_question(
            stem=question,
            correct=correct,
            wrongs=wrongs,
            hint="เลือกคำอธิบายที่ใช้ตำแหน่งและแรงโน้มถ่วงในแบบจำลอง ไม่ใช่เงาหรือเมฆ",
        )


