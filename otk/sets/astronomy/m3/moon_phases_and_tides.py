@question_type(
    "astro.moon_phase_fluency",
    display_name={"th": "ข้างขึ้นข้างแรม: อธิบายเวลาขึ้นตกและชนิดของน้ำ"},
    level={"th": "ม.3"}, subject=ASTRONOMY, topic=SPACE,
)
class MoonPhaseFluency(QuestionType):
    """Link phase, rise time, and tide type, and shift one moonrise by a day."""

    def build(self, rng: Random, **params) -> GeneratedQuestion:
        which = rng.randrange(3)
        if which == 0:
            phase, rise = rng.choice(MOON_RISE_TIMES)
            wrongs = tuple(time for time in MOON_RISE_WRONG_TIMES if time != rise)
            return _moon_question(
                stem=f"จากแบบจำลองการโคจรของดวงจันทร์ คืนที่เห็น{phase} ดวงจันทร์ขึ้นเวลาใดโดยประมาณ",
                correct=rise,
                wrongs=wrongs,
                hint="วางดวงจันทร์ในวงโคจร แล้วดูว่าผู้สังเกตบนโลกหันไปเห็นดวงจันทร์ตอนที่โลกหมุนถึงช่วงเวลาใด",
            )
        if which == 1:
            hour = rng.randrange(17, 22)
            minute = rng.choice((0, 10, 20, 30, 40))
            start = hour * 60 + minute
            return _moon_question(
                stem=(f"คืนนี้ดวงจันทร์ขึ้นเวลา {_clock(start)} และโดยเฉลี่ยดวงจันทร์ขึ้นช้าลง "
                      "วันละประมาณ 50 นาที คืนพรุ่งนี้ดวงจันทร์จะขึ้นเวลาใดโดยประมาณ"),
                correct=_clock(start + 50),
                wrongs=(
                    _clock(start - 50),
                    _clock(start),
                    _clock(start + 100),
                ),
                hint="ใช้ข้อมูลที่โจทย์ให้: เวลาขึ้นของคืนถัดไปช้ากว่าคืนนี้ประมาณ 50 นาที",
            )
        phase, tide, reason = rng.choice(MOON_TIDE_TYPES)
        opposite = "น้ำตาย" if tide == "น้ำเกิด" else "น้ำเกิด"
        other_reason = next(
            item[2] for item in MOON_TIDE_TYPES if item[1] == opposite
        )
        return _moon_question(
            stem=f"คืนที่เห็น{phase} ชายฝั่งจะเกิดน้ำชนิดใด และเพราะเหตุใด",
            correct=f"{tide} เพราะ{reason}",
            wrongs=(
                f"{opposite} เพราะ{other_reason}",
                f"{opposite} เพราะ{reason}",
                f"{tide} เพราะดวงจันทร์อยู่ใกล้โลกที่สุดในคืนนั้น",
            ),
            hint="วาดแนวโลก–ดวงจันทร์และแนวโลก–ดวงอาทิตย์ แล้วดูว่าสองแนวนี้เสริมกันหรือตั้งฉากกัน",
        )


