def _not(right: str) -> tuple[str, ...]:
    return tuple(r for r in REGIONS if r != right)


@question_type(
    "geog.region_landform_p6",
    display_name={"th": "บอกลักษณะภูมิประเทศเด่นของแต่ละภาคในประเทศไทย"},
    level=P6, subject=SUBJECT, topic=TOPIC,
)
@stage(2)
class RegionLandform(ConceptBankType):
    ITEMS = [
        Concept("ภาคใดเป็นเทือกเขาสลับกับหุบเขา และมีดอยอินทนนท์ซึ่งเป็นยอดเขาสูงที่สุดของประเทศไทย",
                NORTH, _not(NORTH)),
        Concept("ภาคใดเป็นที่ราบสูงที่เรียกว่าที่ราบสูงโคราช มีแม่น้ำมูลและแม่น้ำชีไหลผ่าน",
                NORTHEAST, _not(NORTHEAST)),
        Concept("ภาคใดเป็นที่ราบลุ่มแม่น้ำเจ้าพระยา ซึ่งมีดินตะกอนอุดมสมบูรณ์", CENTRAL, _not(CENTRAL)),
        Concept("ภาคใดมีเทือกเขาจันทบุรีและที่ราบชายฝั่งทะเลด้านอ่าวไทย", EAST, _not(EAST)),
        Concept("ภาคใดมีเทือกเขาตะนาวศรีเป็นแนวพรมแดนกับเมียนมา และมีป่าไม้อุดมสมบูรณ์", WEST, _not(WEST)),
        Concept("ภาคใดเป็นคาบสมุทร มีชายฝั่งทะเลทั้งด้านอ่าวไทยและด้านทะเลอันดามัน", SOUTH, _not(SOUTH)),
    ]


