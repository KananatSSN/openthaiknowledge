"""Write the guides to ``otk/sets``: ``INDEX.md`` and one README per subject.

``INDEX.md`` lists every unit file with the keys of the sets in it; each
subject's ``README.md`` lists its units level by level with their indicators.
Both are generated from the registry and the unit files' docstrings, so they
never drift. ``otk/tests/test_sets_layout.py`` fails when they are stale.

    python -m otk.tools.sets_index            # rewrite them
    python -m otk.tools.sets_index --check    # exit 1 if any is stale
"""

from __future__ import annotations

import argparse
import collections
import sys
from pathlib import Path

from otk.core import REGISTRY, catalog

SETS = Path(__file__).resolve().parents[1] / "sets"
# The subject names the catalog uses.
SUBJECTS = {
    "math": "คณิตศาสตร์", "physics": "ฟิสิกส์", "chemistry": "เคมี", "biology": "ชีวะ",
    "earth_science": "ธรณีวิทยา", "astronomy": "ดาราศาสตร์",
    "computing": "วิทยาการคำนวณ", "design_technology": "การออกแบบและเทคโนโลยี",
    "general_science": "วิทยาศาสตร์ทั่วไป",
}
LEVELS = (*(f"p{n}" for n in range(1, 7)), *(f"m{n}" for n in range(1, 7)),
          "calculus1", "calculus2", "quick_math", "olympiad")
LEVEL_NAMES = {**{f"p{n}": f"ป.{n}" for n in range(1, 7)}, **{f"m{n}": f"ม.{n}" for n in range(1, 7)},
               "calculus1": "แคลคูลัส 1", "calculus2": "แคลคูลัส 2",
               "quick_math": "เทคนิคคิดเลขเร็ว", "olympiad": "โอลิมปิก (สอวน.)"}
HEADER = "<!-- Generated by `python -m otk.tools.sets_index`; do not edit by hand. -->\n\n"


def units() -> dict[Path, dict]:
    """``unit file -> {title, indicators, keys}``, in registry order."""
    rows = {r["key"]: r for r in catalog()}
    out: dict[Path, dict] = {}
    for key, qt in REGISTRY.items():
        module = sys.modules[type(qt).__module__]
        path = Path(module.__file__).resolve()
        if SETS not in path.parents or path.parent.parent.parent != SETS:
            continue
        unit = out.setdefault(path, {"title": (module.__doc__ or path.stem).strip().split("\n")[0],
                                     "indicators": [], "keys": []})
        unit["keys"].append(key)
        for code in rows[key]["indicator_codes"]:
            if code not in unit["indicators"]:
                unit["indicators"].append(code)
    return out


def _by_subject(found: dict[Path, dict]):
    grouped = collections.defaultdict(lambda: collections.defaultdict(list))
    for path in sorted(found):
        grouped[path.parent.parent.name][path.parent.name].append(path)
    return grouped


def index(found: dict[Path, dict]) -> str:
    out = [HEADER, "# Problem sets by unit\n\n",
           f"{sum(len(u['keys']) for u in found.values()):,} sets in {len(found):,} unit files. "
           "Each subject's `README.md` lists its units with their indicators.\n"]
    grouped = _by_subject(found)
    for subject in SUBJECTS:
        if subject not in grouped:
            continue
        out.append(f"\n## {subject} — {SUBJECTS[subject]}\n")
        for level in LEVELS:
            if level not in grouped[subject]:
                continue
            out.append(f"\n### {level} — {LEVEL_NAMES[level]}\n\n| File | Unit | Sets |\n|---|---|---|\n")
            for path in grouped[subject][level]:
                u = found[path]
                keys = ", ".join(f"`{k}`" for k in u["keys"])
                out.append(f"| [`{path.name}`]({subject}/{level}/{path.name}) | {u['title']} | {keys} |\n")
    return "".join(out)


def readme(subject: str, levels: dict[str, list[Path]], found: dict[Path, dict]) -> str:
    total = sum(len(found[p]["keys"]) for paths in levels.values() for p in paths)
    files = sum(len(paths) for paths in levels.values())
    out = [HEADER, f"# {SUBJECTS[subject]} (`{subject}`)\n\n",
           f"{total:,} sets in {files:,} unit files, one folder per level and one file per "
           "curriculum unit. The keys of each file's sets are in [`../INDEX.md`](../INDEX.md).\n"]
    for level in LEVELS:
        if level not in levels:
            continue
        out.append(f"\n## {level} — {LEVEL_NAMES[level]}\n\n| File | Unit | Indicators | Sets |\n|---|---|---|---:|\n")
        for path in levels[level]:
            u = found[path]
            indicators = ", ".join(u["indicators"]) or "—"
            out.append(f"| [`{path.stem}`]({level}/{path.name}) | {u['title']} | {indicators} | {len(u['keys'])} |\n")
    return "".join(out)


def documents() -> dict[Path, str]:
    found = units()
    docs = {SETS / "INDEX.md": index(found)}
    for subject, levels in _by_subject(found).items():
        docs[SETS / subject / "README.md"] = readme(subject, levels, found)
    return docs


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if a document is stale")
    args = parser.parse_args()
    stale = []
    for path, text in documents().items():
        if path.exists() and path.read_text("utf-8") == text:
            continue
        stale.append(path)
        if not args.check:
            path.write_text(text, "utf-8")
    verb = "stale" if args.check else "wrote"
    for path in stale:
        print(f"{verb}: {path.relative_to(SETS.parents[1])}")
    sys.exit(1 if args.check and stale else 0)


if __name__ == "__main__":
    main()
