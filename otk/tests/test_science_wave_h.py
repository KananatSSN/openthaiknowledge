def test_every_widened_key_is_registered_and_complete_in_stages():
    assert SCIENCE_WAVE_H_KEYS <= set(REGISTRY)
    # The generator indicator's trio carries two stems (``generator_work`` and
    # ``generator_source``) from Wave D; it is checked as one topic.
    # Some older topics were built without one of the three stages (the ม.3
    # mirror and lens pairs have no Fluency set), so a topic is complete when
    # every stage it actually has is widened.
    # Single-set topics (``phys.dispersion``, ``elec.circuit_type``) carry no
    # stage suffix and stand alone.
    staged = {key for key in SCIENCE_WAVE_H_KEYS
              if key.rsplit("_", 1)[-1] in ("foundation", "fluency", "application", "scenario")}
    stems = {key.rsplit("_", 1)[0] for key in staged} - {"phys.generator_work", "phys.generator_source"}
    for stem in stems:
        stages = [f"{stem}_{stage}" for stage in ("foundation", "fluency", "application")]
        assert any(key in REGISTRY for key in stages), stem
        for key in stages:
            if key in REGISTRY:
                assert key in SCIENCE_WAVE_H_KEYS, key


