"""ข้อ 28 — ความน่าจะเป็นที่กบไม่กระโดดครั้งละ 3 ขั้น

กบตัวหนึ่งต้องการกระโดดขึ้นบันได โดยกบสามารถกระโดดขึ้นบันไดได้ครั้งละ 1, 2 หรือ 3
ขั้นเท่านั้น (เช่น หากมีบันได 3 ขั้น กบตัวนี้จะมีวิธีกระโดดขึ้นบันไดทั้งหมด 4 วิธี)
ถ้าบันไดมี 7 ขั้น จงหาความน่าจะเป็นที่กบตัวนี้ไม่มีการกระโดดขึ้นบันไดครั้งละ 3 ขั้นเลย

Every way of climbing is a **composition** of 7 into parts from {1, 2, 3}, and
the worked example in the question (3 stairs → 4 ways) confirms that reading.
Both counts are one-line recurrences:

    all ways      T(n) = T(n−1) + T(n−2) + T(n−3):  1, 1, 2, 4, 7, 13, 24, **44**
    without a 3   F(n) = F(n−1) + F(n−2):           1, 1, 2, 3, 5,  8, 13, **21**

so the probability is

    21/44

The 3-free count is the Fibonacci sequence and the unrestricted one is the
tribonacci sequence — the answer is the ratio of two adjacent members of two
famous sequences, which is why it does not simplify.

Note the model: each *way* is equally likely, not each jump. Weighting the jumps
uniformly instead would give a different number.

``solve`` runs the two recurrences. ``check`` enumerates the climbs themselves —
every actual sequence of jumps — and counts how many avoid the largest step.
"""

from __future__ import annotations

from fractions import Fraction

#: how many stairs, which jumps are allowed, and which one must be avoided.
PARAMS = {"stairs": 7, "jumps": (1, 2, 3), "avoid": 3}
ANSWER = Fraction(21, 44)
VARIANTS = [
    {"stairs": 5, "jumps": (1, 2, 3), "avoid": 3},
    {"stairs": 10, "jumps": (1, 2, 3), "avoid": 3},
    {"stairs": 7, "jumps": (1, 2, 3), "avoid": 2},
    {"stairs": 8, "jumps": (1, 2, 4), "avoid": 4},
    {"stairs": 7, "jumps": (1, 2, 3), "avoid": 1},     # 1 is needed for odd gaps
    {"stairs": 0, "jumps": (1, 2, 3), "avoid": 3},
]


def _count(stairs: int, jumps) -> int:
    """Compositions of ``stairs`` using the given part sizes."""
    ways = [0] * (stairs + 1)
    ways[0] = 1
    for total in range(1, stairs + 1):
        ways[total] = sum(ways[total - j] for j in jumps if j <= total)
    return ways[stairs]


def solve(stairs=7, jumps=(1, 2, 3), avoid=3):
    """(ways avoiding the step) / (all ways), by two recurrences."""
    if stairs < 1 or not jumps or avoid not in jumps:
        return None
    total = _count(stairs, jumps)
    if total == 0:
        return None
    kept = _count(stairs, tuple(j for j in jumps if j != avoid))
    return Fraction(kept, total)


def check(stairs=7, jumps=(1, 2, 3), avoid=3):
    """Independent: enumerate the climbs themselves and count.

    Every sequence of jumps that lands exactly on the top stair is generated by
    depth-first search, and the ones containing the avoided step are counted
    against the rest. No recurrence is used, so the recurrences' base cases
    cannot hide a mistake.
    """
    if stairs < 1 or not jumps or avoid not in jumps:
        return None
    if len(jumps) ** stairs > 5 * 10 ** 6:
        return None

    total = 0
    clean = 0
    stack = [(0, False)]
    while stack:
        height, used = stack.pop()
        if height == stairs:
            total += 1
            if not used:
                clean += 1
            continue
        for jump in jumps:
            if height + jump <= stairs:
                stack.append((height + jump, used or jump == avoid))
    if total == 0:
        return None
    return Fraction(clean, total)
